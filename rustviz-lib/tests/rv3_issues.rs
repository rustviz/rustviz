//! RustViz 3 issue tests: every open `bug` issue with a runnable repro,
//! as facts the RustViz 3 fact layer must get right (states, loans,
//! borrow ends, drops, event order), independent of tooltip wording.
//!
//! A case is `rustviz-plugin/tests/rv3_issues/<issue>_<slug>.rs` (the
//! repro) plus `<same>.expect.toml` (format: `rustviz-plugin/tests/rv3_issues/README.md`).
//! Its assertions are either derived from rustc (`[oracle]`, written by
//! `RV3_ISSUES_GEN=1`) or hand-written from the issue and checked against
//! rustc / MIR (`src = "issue"`).
//!
//! Tests:
//! - `rv3_issue_cases_well_formed` (always): every case parses, uses the
//!   vocabulary, and its `[oracle]` block was generated from the `.rs` as
//!   it is now.
//! - `rv3_issue_cases_against_facts`: runs each case's program through
//!   the installed plugin with `RV3_FACTS=<file>` (or reads
//!   `$RV3_FACTS_DIR/<case>.facts.json`), checks every assertion and
//!   prints "N of M issue tests pass". A plugin that writes no fact dump
//!   (2.x) skips it. Report-only unless `RV3_ISSUES_STRICT=1`, which
//!   fails on a case that fails without `xfail` or passes with one, on
//!   any case whose facts couldn't be read (a missing `RV3_FACTS_DIR` or
//!   dump, a plugin failure), and when no case was checked at all.
//! - `rv3_issue_cases_gen` (`RV3_ISSUES_GEN=1`): (re)derives the
//!   `[oracle]` block of each case (`RV3_ISSUES_ONLY=<prefix>,..` narrows)
//!   and reports hand-written states rustc contradicts.
// `why` / `note` fields document a case for its readers; the harness
// doesn't read them.
#![allow(dead_code)]

