#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct LoanA {
    /// The row the borrow is taken on.
    row: u32,
    lender: String,
    kind: Option<String>,
    holder: Option<String>,
    /// Exactly these ends, one per CFG edge where the loan goes out of
    /// scope: `9` (an end on row 9, on any edge) or `[5, 6]` (an end on
    /// row 5 on the path that next runs row 6; rows holding only braces
    /// or `else` in between are skipped).
    ends: Option<Vec<EndSpec>>,
    #[serde(default)]
    ends_include: Vec<u32>,
    #[serde(default)]
    ends_exclude: Vec<u32>,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct DropA {
    row: u32,
    place: String,
    #[serde(default = "any_how")]
    how: String,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone, Copy, PartialEq)]
#[serde(untagged)]
enum EndSpec {
    Row(u32),
    Edge([u32; 2]),
}

impl EndSpec {
    fn row(self) -> u32 {
        match self {
            EndSpec::Row(r) | EndSpec::Edge([r, _]) => r,
        }
    }
}

fn any_how() -> String {
    "any".into()
}

