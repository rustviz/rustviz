fn cases_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../rustviz-plugin/tests/rv3_issues")
}

/// (name, program, expect.toml text) of every case, sorted, narrowed by
/// `RV3_ISSUES_ONLY`.
fn cases() -> Vec<(String, String, String)> {
    let dir = cases_dir();
    let mut out = Vec::new();
    for e in std::fs::read_dir(&dir).unwrap_or_else(|e| panic!("read {dir:?}: {e}")) {
        let p = e.unwrap().path();
        let Some(name) = p.file_name().and_then(|n| n.to_str()).and_then(|n| n.strip_suffix(".expect.toml")) else { continue };
        let rs = dir.join(format!("{name}.rs"));
        let src = std::fs::read_to_string(&rs).unwrap_or_else(|e| panic!("{name}: no {rs:?}: {e}"));
        out.push((name.to_owned(), src, std::fs::read_to_string(&p).unwrap()));
    }
    if let Ok(only) = std::env::var("RV3_ISSUES_ONLY") {
        let pre: Vec<&str> = only.split(',').filter(|p| !p.is_empty()).collect();
        out.retain(|(n, _, _)| pre.iter().any(|p| n.starts_with(p)));
    }
    out.sort();
    out
}

/// FNV-1a 64 of the program: stable across Rust versions.
fn source_hash(src: &str) -> String {
    let mut h: u64 = 0xcbf29ce484222325;
    for b in src.bytes() {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn toolchain() -> String {
    rustviz_lib::toolchain_channel().to_owned()
}

/// Every assertion of a case, flattened: (src, fn, description, check).
enum Check {
    State { row: u32, place: String, is: String },
    Lent { row: u32, place: String, kind: Option<String>, holder: Option<String>, absent: bool },
    Loan(LoanA),
    Drop { row: u32, place: String, how: String, absent: bool },
    Event { row: u32, ev: String, absent: bool },
    Order { row: u32, events: Vec<String> },
}

struct Assertion {
    src: String,
    func: String,
    what: String,
    check: Check,
}

fn assertions(c: &Case) -> Vec<Assertion> {
    let f = |o: &Option<String>| o.clone().unwrap_or_else(|| c.func.clone());
    let mut out = Vec::new();
    for s in &c.state {
        out.push(Assertion { src: s.src.clone(), func: f(&s.func), what: format!("after row {}: {} is {}", s.row, s.place, s.is),
            check: Check::State { row: s.row, place: s.place.clone(), is: s.is.clone() } });
    }
    for l in &c.lent {
        out.push(Assertion {
            src: l.src.clone(),
            func: f(&l.func),
            what: format!("after row {}: {} {}lent{}{}", l.row, l.place, if l.absent { "not " } else { "" },
                l.kind.as_ref().map_or(String::new(), |k| format!(" {k}")), l.holder.as_ref().map_or(String::new(), |h| format!(" to {h}"))),
            check: Check::Lent { row: l.row, place: l.place.clone(), kind: l.kind.clone(), holder: l.holder.clone(), absent: l.absent },
        });
    }
    for l in &c.loan {
        out.push(Assertion {
            src: l.src.clone(),
            func: f(&l.func),
            what: format!("{}loan of {} on row {}{}{}{}", if l.absent { "no " } else { "" }, l.lender, l.row,
                l.holder.as_ref().map_or(String::new(), |h| format!(" to {h}")),
                l.ends.as_ref().map_or(String::new(), |e| format!(", ends {e:?}")),
                if l.ends_include.is_empty() && l.ends_exclude.is_empty() { String::new() } else { format!(", ends incl {:?} excl {:?}", l.ends_include, l.ends_exclude) }),
            check: Check::Loan(l.clone()),
        });
    }
    for d in &c.drop {
        out.push(Assertion { src: d.src.clone(), func: f(&d.func), what: format!("{}drop ({}) of {} on row {}", if d.absent { "no " } else { "" }, d.how, d.place, d.row),
            check: Check::Drop { row: d.row, place: d.place.clone(), how: d.how.clone(), absent: d.absent } });
    }
    for e in &c.event {
        out.push(Assertion { src: e.src.clone(), func: f(&e.func), what: format!("{}`{}` on row {}", if e.absent { "no " } else { "" }, e.ev, e.row),
            check: Check::Event { row: e.row, ev: e.ev.clone(), absent: e.absent } });
    }
    for o in &c.order {
        out.push(Assertion { src: o.src.clone(), func: f(&o.func), what: format!("on row {}, in order: {:?}", o.row, o.events),
            check: Check::Order { row: o.row, events: o.events.clone() } });
    }
    for s in c.oracle.iter().flat_map(|o| &o.states) {
        let p: Vec<&str> = s.split_whitespace().collect();
        if let [func, row, place, is] = p[..] {
            out.push(Assertion { src: "oracle".into(), func: func.into(), what: format!("after row {row}: {place} is {is}"),
                check: Check::State { row: row.parse().unwrap_or(0), place: place.into(), is: is.into() } });
        }
    }
    out
}

/// What's wrong with a case's text (empty: well formed).
fn problems(name: &str, src: &str, text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let c: Case = match toml::from_str(text) {
        Ok(c) => c,
        Err(e) => return vec![format!("doesn't parse: {e}")],
    };
    if !name.starts_with(&format!("{}_", c.issue)) {
        out.push(format!("file name doesn't start with its issue number {}_", c.issue));
    }
    if !c.cluster.starts_with('C') || c.title.is_empty() {
        out.push("cluster (Cnn) and title are required".into());
    }
    if let Some(x) = &c.xfail {
        if !PHASES.contains(&x.as_str()) {
            out.push(format!("xfail {x:?} is not one of {PHASES:?}"));
        }
    }
    let n_lines = src.lines().count() as u32;
    let rows: Vec<u32> = c.state.iter().map(|s| s.row).chain(c.lent.iter().map(|s| s.row)).chain(c.loan.iter().map(|s| s.row))
        .chain(c.loan.iter().flat_map(|l| l.ends.iter().flatten().chain(&l.ends_include).chain(&l.ends_exclude).copied()))
        .chain(c.drop.iter().map(|s| s.row)).chain(c.event.iter().map(|s| s.row)).chain(c.order.iter().map(|s| s.row)).collect();
    if let Some(r) = rows.iter().find(|&&r| r == 0 || r > n_lines) {
        out.push(format!("row {r} is not a line of the program (1..={n_lines})"));
    }
    for a in assertions(&c) {
        if a.src != "oracle" && a.src != "issue" {
            out.push(format!("{}: src must be \"oracle\" or \"issue\", not {:?}", a.what, a.src));
        }
        match &a.check {
            Check::State { is, .. } if !STATES.contains(&is.as_str()) => out.push(format!("{}: state {is:?} not in {STATES:?}", a.what)),
            Check::Lent { kind: Some(k), .. } | Check::Loan(LoanA { kind: Some(k), .. }) if !["shared", "mut", "unique", "exclusive"].contains(&k.as_str()) => {
                out.push(format!("{}: kind {k:?} not shared|mut|unique|exclusive", a.what))
            }
            Check::Drop { how, .. } if !DROP_HOW.contains(&how.as_str()) => out.push(format!("{}: how {how:?} not in {DROP_HOW:?}", a.what)),
            Check::Event { ev, .. } => {
                if let Err(e) = Pat::parse(ev) {
                    out.push(format!("{}: {e}", a.what));
                }
            }
            Check::Order { events, .. } => {
                if events.len() < 2 {
                    out.push(format!("{}: an order needs two events or more", a.what));
                }
                for ev in events {
                    if let Err(e) = Pat::parse(ev) {
                        out.push(format!("{}: {e}", a.what));
                    }
                }
            }
            _ => {}
        }
    }
    if c.state.iter().any(|s| s.src == "oracle") {
        out.push("hand-written [[state]] with src = \"oracle\": put rustc-derived states in the generated block".into());
    }
    match &c.oracle {
        None => out.push("no [oracle] block: run RV3_ISSUES_GEN=1".into()),
        Some(o) => {
            if o.source_hash != source_hash(src) {
                out.push("[oracle] is stale (the program changed): run RV3_ISSUES_GEN=1".into());
            }
            if !text.contains(GEN_MARK) {
                out.push("the generated block lost its marker line".into());
            }
        }
    }
    let n_issue = assertions(&c).iter().filter(|a| a.src == "issue").count();
    if n_issue == 0 && c.duplicate_of.is_none() {
        out.push("no hand-written (src = \"issue\") assertion: what does the issue say is true?".into());
    }
    out
}

#[test]
fn rv3_issue_cases_well_formed() {
    let mut bad = String::new();
    let all = cases();
    for (name, src, text) in &all {
        for p in problems(name, src, text) {
            let _ = writeln!(bad, "{name}: {p}");
        }
    }
    assert!(bad.is_empty(), "malformed RV3 issue cases:\n{bad}");
    eprintln!("rv3_issue_cases_well_formed: {} cases", all.len());
}

// ─── Facts (adapter) ────────────────────────────────────────────────
//
// The harness reads the fact dump through this adapter, so the dump's
// shape can change without touching the cases. Two shapes are read:
// the RustViz 3 fact layer's (`{"version": 1, "bodies": [..]}`,
// `rustviz-plugin/src/facts/schema.rs`) and the spike's (a bare array of
// bodies whose `lent` is keyed by lender with "kind:L<n>->holder" strings,
// branch spike/rustviz3).

#[derive(Debug, Clone)]
struct Lent {
    loan: usize,
    kind: String,
    holder: String,
}

#[derive(Debug, Clone, Default)]
struct RowF {
    state: BTreeMap<String, String>,
    /// column -> (fields moved on every path, fields moved on some paths)
    parts: BTreeMap<String, (Vec<String>, Vec<String>)>,
    lent: BTreeMap<String, Vec<Lent>>,
    facts: Vec<Value>,
}

#[derive(Debug, Clone)]
struct LoanF {
    line: u32,
    lender: String,
    kind: String,
    holders: Vec<String>,
    end_lines: Vec<u32>,
}

#[derive(Debug, Clone)]
struct BodyF {
    func: String,
    rows: BTreeMap<u32, RowF>,
    loans: Vec<LoanF>,
}

fn strs(v: &Value) -> Vec<String> {
    v.as_array().into_iter().flatten().filter_map(|x| x.as_str().map(str::to_owned)).collect()
}

fn nums(v: &Value) -> Vec<u32> {
    v.as_array().into_iter().flatten().filter_map(|x| x.as_u64().map(|n| n as u32)).collect()
}

/// Whether a loan of `lender` restricts column `col` (one is a field path
/// of the other; `*b`, `v[_]` restrict `b`, `v`).
fn overlaps(lender: &str, col: &str) -> bool {
    let l = lender.trim_start_matches('*');
    let l = l.split("[").next().unwrap_or(l);
    l == col || l.starts_with(&format!("{col}.")) || col.starts_with(&format!("{l}."))
}

fn load_facts(v: &Value) -> Result<Vec<BodyF>, String> {
    let (bodies, spike) = match v {
        Value::Array(a) => (a.clone(), true),
        Value::Object(o) => match (o.get("version").and_then(Value::as_u64), o.get("bodies")) {
            (Some(1), Some(Value::Array(b))) => (b.clone(), false),
            (ver, _) => return Err(format!("fact dump version {ver:?}: teach load_facts this shape")),
        },
        _ => return Err("fact dump is neither an object nor an array".into()),
    };
    let mut out = Vec::new();
    for b in &bodies {
        let mut rows = BTreeMap::new();
        for r in b["rows"].as_array().into_iter().flatten() {
            let line = r["line"].as_u64().unwrap_or(0) as u32;
            let state: BTreeMap<String, String> = r["state"].as_object().into_iter().flatten()
                .filter_map(|(k, s)| s.as_str().map(|s| (k.clone(), s.to_owned()))).collect();
            let mut lent: BTreeMap<String, Vec<Lent>> = BTreeMap::new();
            for (k, ls) in r["lent"].as_object().into_iter().flatten() {
                for l in ls.as_array().into_iter().flatten() {
                    if spike {
                        // "shared:L0->c"
                        let s = l.as_str().unwrap_or("");
                        let (kind, rest) = s.split_once(':').unwrap_or(("", s));
                        let (id, holder) = rest.split_once("->").unwrap_or((rest, ""));
                        let lt = Lent { loan: id.trim_start_matches('L').parse().unwrap_or(usize::MAX), kind: kind.into(), holder: holder.into() };
                        let mut cols: Vec<String> = state.keys().filter(|c| overlaps(k, c)).cloned().collect();
                        cols.push(k.clone());
                        cols.sort();
                        cols.dedup();
                        for c in cols {
                            lent.entry(c).or_default().push(lt.clone());
                        }
                    } else {
                        lent.entry(k.clone()).or_default().push(Lent {
                            loan: l["loan"].as_u64().unwrap_or(u64::MAX) as usize,
                            kind: l["kind"].as_str().unwrap_or("").into(),
                            holder: l["holder"].as_str().unwrap_or("").into(),
                        });
                    }
                }
            }
            let parts = r["parts"].as_object().into_iter().flatten()
                .map(|(k, p)| (k.clone(), (strs(&p["moved"]), strs(&p["maybe"])))).collect();
            let facts = r["facts"].as_array().cloned().unwrap_or_default();
            rows.insert(line, RowF { state, parts, lent, facts });
        }
        let loans = b["loans"].as_array().into_iter().flatten().map(|l| LoanF {
            line: l["line"].as_u64().unwrap_or(0) as u32,
            lender: l["lender"].as_str().unwrap_or("").into(),
            kind: l["kind"].as_str().unwrap_or("").into(),
            holders: strs(&l["holders"]),
            end_lines: nums(&l["end_lines"]),
        }).collect();
        out.push(BodyF { func: b["func"].as_str().unwrap_or("").into(), rows, loans });
    }
    Ok(out)
}

/// The fact dump of `src` from the installed plugin (`cargo rv-plugin`
/// with `RV3_FACTS`), or `$RV3_FACTS_DIR/<name>.facts.json`. Ok(None):
/// the plugin wrote no dump (a build without the fact layer).
fn facts_of(name: &str, src: &str) -> Result<Option<Value>, String> {
    if let Ok(dir) = std::env::var("RV3_FACTS_DIR") {
        let p = Path::new(&dir).join(format!("{name}.facts.json"));
        return match std::fs::read_to_string(&p) {
            Ok(t) => serde_json::from_str(&t).map(Some).map_err(|e| format!("{p:?}: {e}")),
            Err(_) => Ok(None),
        };
    }
    let tmp = tempfile::tempdir().map_err(|e| e.to_string())?;
    let proj = tmp.path().join("user-code");
    std::fs::create_dir_all(proj.join("src")).map_err(|e| e.to_string())?;
    std::fs::write(proj.join("Cargo.toml"), "[package]\nname = \"user-code\"\nversion = \"0.1.0\"\nedition = \"2024\"\n").map_err(|e| e.to_string())?;
    std::fs::write(proj.join("rust-toolchain.toml"), include_str!("../../rust-toolchain.toml")).map_err(|e| e.to_string())?;
    std::fs::write(proj.join("src/lib.rs"), src).map_err(|e| e.to_string())?;
    let dump = tmp.path().join("facts.json");
    let out = Command::new("cargo")
        .arg("rv-plugin")
        .current_dir(&proj)
        .env("CARGO_TERM_COLOR", "never")
        .env("RV3_FACTS", &dump)
        .env_remove("CARGO_TARGET_DIR")
        .env_remove("CARGO_BUILD_TARGET_DIR")
        .output()
        .map_err(|e| format!("run cargo rv-plugin: {e}"))?;
    if !out.status.success() {
        return Err(format!("cargo rv-plugin failed: {}", String::from_utf8_lossy(&out.stderr).chars().take(600).collect::<String>()));
    }
    match std::fs::read_to_string(&dump) {
        Ok(t) => {
            // `RV3_FACTS_SAVE=<dir>` keeps the dumps (for `RV3_FACTS_DIR`).
            if let Ok(save) = std::env::var("RV3_FACTS_SAVE") {
                let _ = std::fs::create_dir_all(&save);
                let _ = std::fs::write(Path::new(&save).join(format!("{name}.facts.json")), &t);
            }
            serde_json::from_str(&t).map(Some).map_err(|e| format!("fact dump: {e}"))
        }
        Err(_) => Ok(None),
    }
}

// ─── Checking ───────────────────────────────────────────────────────

/// An event pattern: `<kind> <place>[ -> <target>]`; `_` matches any.
struct Pat {
    kind: String,
    place: String,
    target: Option<String>,
}

impl Pat {
    fn parse(s: &str) -> Result<Pat, String> {
        let (head, target) = match s.split_once("->") {
            Some((h, t)) => (h.trim(), Some(t.trim().to_owned())),
            None => (s.trim(), None),
        };
        let mut w = head.split_whitespace();
        let (Some(kind), Some(place), None) = (w.next(), w.next(), w.next()) else {
            return Err(format!("event {s:?} isn't `<kind> <place>[ -> <target>]`"));
        };
        if !EVENT_KINDS.contains(&kind) {
            return Err(format!("event kind {kind:?} not in {EVENT_KINDS:?}"));
        }
        Ok(Pat { kind: kind.into(), place: place.into(), target })
    }

    fn matches(&self, f: &Value) -> bool {
        let s = |k: &str| f[k].as_str().unwrap_or("");
        let eq = |want: &str, got: &str| want == "_" || want == got;
        let tgt = |got: &str| self.target.as_deref().is_none_or(|t| eq(t, got));
        match (self.kind.as_str(), s("ev")) {
            ("init", "Init") => f["reassign"] != Value::Bool(true) && eq(&self.place, s("path")),
            ("reassign", "Init") => f["reassign"] == Value::Bool(true) && eq(&self.place, s("path")),
            ("move", "Move") | ("copy", "Copy") => eq(&self.place, s("path")) && tgt(s("to")),
            ("borrow", "Borrow") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-shared", "Borrow") => s("kind") == "shared" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-mut", "Borrow") => s("kind") != "shared" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("end", "BorrowEnd") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("repoint", "Repoint") => eq(&self.place, s("holder")),
            ("drop", "Drop") | ("scope-end", "ScopeEnd") => eq(&self.place, s("path")),
            ("tempdrop", "TempDrop") => self.place == "_" || s("what").contains(self.place.as_str()),
            _ => false,
        }
    }
}

fn body<'a>(facts: &'a [BodyF], func: &str) -> Option<&'a BodyF> {
    facts.iter().find(|b| b.func == func).or_else(|| facts.iter().find(|b| b.func.ends_with(&format!("::{func}"))))
}

/// The state after row `row`: the row's own, or (a row with no MIR
/// location) the last row above it that has one.
fn row_after(b: &BodyF, row: u32) -> Option<&RowF> {
    b.rows.range(..=row).rev().find(|(_, r)| !r.state.is_empty()).map(|(_, r)| r)
}

/// Every fact on row `row`, plus drops the dump attributes to an early
/// exit on `row` (their MIR span is the scope's `}`).
fn row_facts(b: &BodyF, row: u32) -> Vec<&Value> {
    let mut out: Vec<&Value> = b.rows.get(&row).into_iter().flat_map(|r| &r.facts).collect();
    for (l, r) in &b.rows {
        if *l != row {
            out.extend(r.facts.iter().filter(|f| f["early_exit"].as_u64() == Some(row as u64)));
        }
    }
    out
}

fn kind_ok(want: &Option<String>, got: &str) -> bool {
    match want.as_deref() {
        None => true,
        Some("exclusive") => got == "mut" || got == "unique",
        Some(k) => k == got,
    }
}

/// Ok(()) or what the facts say instead.
fn check(a: &Assertion, facts: &[BodyF]) -> Result<(), String> {
    let Some(b) = body(facts, &a.func) else { return Err(format!("no body `{}` in the dump", a.func)) };
    match &a.check {
        Check::State { row, place, is } => {
            let r = row_after(b, *row);
            let st = r.and_then(|r| r.state.get(place)).map(String::as_str);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            let parts = r.and_then(|r| r.parts.get(place));
            let any_parts = parts.is_some_and(|(m, may)| !m.is_empty() || !may.is_empty());
            let excl = lent.iter().any(|l| l.kind != "shared");
            let ok = match is.as_str() {
                "own" => st == Some("own") && lent.is_empty() && !any_parts,
                "shared" => st == Some("own") && !lent.is_empty() && !excl,
                "mut" => matches!(st, Some("own" | "partly")) && excl,
                "moved" => st == Some("moved"),
                "maybe-moved" => st == Some("maybe"),
                "moved*" => matches!(st, Some("moved" | "maybe")),
                "partly" => st == Some("partly"),
                "partly*" => st == Some("partly") || any_parts,
                "unassigned" => st == Some("unassigned"),
                "maybe-unassigned" => st == Some("maybe"),
                "unassigned*" => matches!(st, Some("unassigned" | "maybe")),
                "absent" => st.is_none(),
                _ => false,
            };
            let got = format!("{} lent {:?} parts {:?}", st.unwrap_or("(no state)"),
                lent.iter().map(|l| format!("{}:L{}->{}", l.kind, l.loan, l.holder)).collect::<Vec<_>>(), parts);
            if ok { Ok(()) } else { Err(got) }
        }
        Check::Lent { row, place, kind, holder, absent } => {
            let r = row_after(b, *row);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            let hit = lent.iter().any(|l| kind_ok(kind, &l.kind) && holder.as_deref().is_none_or(|h| h == "_" || h == l.holder));
            let got = format!("lent {:?}", lent.iter().map(|l| format!("{}:L{}->{}", l.kind, l.loan, l.holder)).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Loan(l) => {
            let cands: Vec<&LoanF> = b.loans.iter()
                .filter(|x| x.line == l.row && x.lender == l.lender && kind_ok(&l.kind, &x.kind)
                    && l.holder.as_deref().is_none_or(|h| h == "_" || x.holders.iter().any(|y| y == h)))
                .collect();
            let fits = |x: &&LoanF| {
                let mut e = x.end_lines.clone();
                e.sort();
                e.dedup();
                l.ends.as_ref().is_none_or(|want| {
                    let mut w = want.clone();
                    w.sort();
                    w.dedup();
                    w == e
                }) && l.ends_include.iter().all(|r| e.contains(r)) && !l.ends_exclude.iter().any(|r| e.contains(r))
            };
            let hit = cands.iter().any(fits);
            let got = if cands.is_empty() {
                format!("loans on row {}: {:?}", l.row, b.loans.iter().filter(|x| x.line == l.row)
                    .map(|x| format!("{} {} -> {:?} ends {:?}", x.kind, x.lender, x.holders, x.end_lines)).collect::<Vec<_>>())
            } else {
                format!("{:?}", cands.iter().map(|x| format!("{} {} -> {:?} ends {:?}", x.kind, x.lender, x.holders, x.end_lines)).collect::<Vec<_>>())
            };
            if l.absent { if cands.is_empty() { Ok(()) } else { Err(got) } } else if hit { Ok(()) } else { Err(got) }
        }
        Check::Drop { row, place, how, absent } => {
            let fs = row_facts(b, *row);
            let drops: Vec<&&Value> = fs.iter().filter(|f| {
                let ev = f["ev"].as_str().unwrap_or("");
                (ev == "Drop" || ev == "ScopeEnd") && f["path"].as_str() == Some(place.as_str())
            }).collect();
            let hit = drops.iter().any(|f| {
                let h = f["how"].as_str().unwrap_or("");
                let scope_end = f["ev"] == "ScopeEnd";
                match how.as_str() {
                    "definite" => h == "drops",
                    "conditional" => h == "drops_if_init",
                    "rest" => h == "drops_rest",
                    "none" => scope_end || h == "nothing_to_drop",
                    _ => !scope_end && h != "nothing_to_drop",
                }
            });
            let got = format!("{:?}", drops.iter().map(|f| f.to_string()).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Event { row, ev, absent } => {
            let p = Pat::parse(ev)?;
            let fs = row_facts(b, *row);
            let hit = fs.iter().any(|f| p.matches(f));
            if hit != *absent { Ok(()) } else { Err(format!("row facts: {}", brief(&fs))) }
        }
        Check::Order { row, events } => {
            let pats: Vec<Pat> = events.iter().map(|e| Pat::parse(e)).collect::<Result<_, _>>()?;
            let fs = row_facts(b, *row);
            let mut k = 0;
            for f in &fs {
                if k < pats.len() && pats[k].matches(f) {
                    k += 1;
                }
            }
            if k == pats.len() { Ok(()) } else { Err(format!("row facts in order: {}", brief(&fs))) }
        }
    }
}

fn brief(fs: &[&Value]) -> String {
    fs.iter().map(|f| {
        let s = |k: &str| f[k].as_str().unwrap_or("").to_owned();
        match s("ev").as_str() {
            "Move" | "Copy" => format!("{} {} -> {}", s("ev").to_lowercase(), s("path"), s("to")),
            "Borrow" => format!("borrow {} {} -> {}", s("kind"), s("lender"), s("holder")),
            "BorrowEnd" => format!("end {} -> {}", s("lender"), s("holder")),
            "Init" => format!("init {}", s("path")),
            "Drop" => format!("drop {} [{}]", s("path"), s("how")),
            "Repoint" => format!("repoint {}", s("holder")),
            e => format!("{} {}", e, s("path")),
        }
    }).collect::<Vec<_>>().join("; ")
}

#[test]
fn rv3_issue_cases_against_facts() {
    let all = cases();
    let strict = std::env::var("RV3_ISSUES_STRICT").is_ok_and(|v| v == "1");
    let jobs: usize = std::env::var("RV3_JOBS").ok().and_then(|v| v.parse().ok()).unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let results = std::sync::Mutex::new(Vec::new());
    std::thread::scope(|sc| {
        for _ in 0..jobs {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some((name, src, text)) = all.get(i) else { break };
                let case: Case = match toml::from_str(text) {
                    Ok(c) => c,
                    Err(e) => {
                        results.lock().unwrap().push((name.clone(), None, Err(format!("parse: {e}"))));
                        continue;
                    }
                };
                let r = facts_of(name, src).and_then(|v| v.map(|v| load_facts(&v)).transpose());
                results.lock().unwrap().push((name.clone(), Some(case), r));
            });
        }
    });
    let mut results = results.into_inner().unwrap();
    results.sort_by(|a, b| a.0.cmp(&b.0));
    if results.iter().all(|(_, _, r)| matches!(r, Ok(None))) {
        eprintln!("rv3_issue_cases_against_facts: skipped: the installed plugin writes no RV3_FACTS dump (no fact layer)");
        return;
    }
    let mut report = String::new();
    let (mut pass, mut total) = (0, 0);
    let (mut a_pass, mut a_total) = (BTreeMap::<String, (usize, usize)>::new(), 0);
    let mut by_phase: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    let mut unexpected = Vec::new();
    for (name, case, r) in &results {
        total += 1;
        let Some(case) = case else {
            let _ = writeln!(report, "FAIL {name}: {}", r.as_ref().err().unwrap());
            unexpected.push(name.clone());
            continue;
        };
        let facts = match r {
            Ok(Some(f)) => f,
            Ok(None) => {
                let _ = writeln!(report, "FAIL {name}: no fact dump");
                if case.xfail.is_none() {
                    unexpected.push(name.clone());
                }
                continue;
            }
            Err(e) => {
                let _ = writeln!(report, "FAIL {name}: {e}");
                if case.xfail.is_none() {
                    unexpected.push(name.clone());
                }
                continue;
            }
        };
        let mut fails = Vec::new();
        for a in assertions(case) {
            a_total += 1;
            let e = a_pass.entry(a.src.clone()).or_default();
            e.1 += 1;
            match check(&a, facts) {
                Ok(()) => e.0 += 1,
                Err(got) => fails.push(format!("    [{}] {}: got {}", a.src, a.what, got)),
            }
        }
        let ok = fails.is_empty();
        let phase = case.xfail.clone().unwrap_or_else(|| "-".into());
        let ph = by_phase.entry(phase.clone()).or_default();
        ph.1 += 1;
        if ok {
            pass += 1;
            ph.0 += 1;
        }
        let tag = match (ok, &case.xfail) {
            (true, None) => "pass",
            (true, Some(_)) => {
                unexpected.push(format!("{name} (passes: remove xfail)"));
                "PASS (xfail)"
            }
            (false, Some(_)) => "xfail",
            (false, None) => {
                unexpected.push(name.clone());
                "FAIL"
            }
        };
        let _ = writeln!(report, "{tag} {name} (#{}, {}, xfail {phase})", case.issue, case.cluster);
        for f in fails {
            let _ = writeln!(report, "{f}");
        }
    }
    let _ = writeln!(report, "\n{pass} of {total} issue tests pass");
    for (src, (p, t)) in &a_pass {
        let _ = writeln!(report, "  {src} assertions: {p} of {t} hold");
    }
    let _ = writeln!(report, "  ({a_total} assertions)");
    for (ph, (p, t)) in &by_phase {
        let _ = writeln!(report, "  xfail {ph}: {p} of {t} pass");
    }
    if let Ok(out) = std::env::var("RV3_ISSUES_REPORT") {
        std::fs::write(&out, &report).unwrap();
    }
    eprintln!("{report}");
    if strict {
        assert!(unexpected.is_empty(), "RV3 issue tests: unexpected results:\n  {}", unexpected.join("\n  "));
    }
}

