/// Whether a hand-written state agrees with rustc's.
fn compatible(hand: &str, rustc: &str) -> bool {
    hand == rustc
        || matches!((hand, rustc), ("moved" | "maybe-moved", "moved*") | ("partly", "partly*") | ("unassigned" | "maybe-unassigned", "unassigned*"))
}

#[test]
fn known_crash_verdicts() {
    let k = KnownCrash { issue: 1, panic_at: "data.rs:5179".into(), phase: "P2".into() };
    let panic = "error: internal error at data.rs:5179: boom";
    assert!(crash_verdict(None, true, "").is_ok());
    assert!(crash_verdict(None, false, panic).is_err(), "an unmarked crash fails");
    assert!(crash_verdict(Some(&k), false, panic).is_ok(), "the marked crash is accepted");
    assert!(crash_verdict(Some(&k), false, "internal error at data.rs:9: x").unwrap_err().contains("failed differently"), "another panic site fails");
    assert!(crash_verdict(Some(&k), true, "").unwrap_err().contains("remove known_crash"), "a fixed crash flags the marker");
    // Format: known_crash and xfail are exclusive, phase and issue are checked.
    let toml = "issue = 7\ncluster = \"C01\"\ntitle = \"t\"\nxfail = \"P2\"\n[known_crash]\nissue = 8\npanic_at = \"x\"\nphase = \"P9\"\n";
    let p = problems("7_x", "fn f() {}\n", toml).join(";");
    assert!(p.contains("phase") && p.contains("known_crash issue 8") && p.contains("use one"), "{p}");
}

#[test]
fn rv3_issue_cases_gen() {
    if std::env::var("RV3_ISSUES_GEN").ok().as_deref() != Some("1") {
        return;
    }
    let all = cases();
    let jobs: usize = std::env::var("RV3_JOBS").ok().and_then(|v| v.parse().ok()).unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let notes = std::sync::Mutex::new(Vec::new());
    std::thread::scope(|sc| {
        for _ in 0..jobs {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some((name, src, text)) = all.get(i) else { break };
                let note = gen_one(name, src, text);
                notes.lock().unwrap().push(format!("{name}: {note}"));
            });
        }
    });
    let mut notes = notes.into_inner().unwrap();
    notes.sort();
    eprintln!("{}", notes.join("\n"));
    let failed: Vec<&String> = notes.iter().filter(|n| n.contains("FAILED")).collect();
    assert!(failed.is_empty(), "the oracle failed on {} case(s); their blocks were kept:\n{}", failed.len(),
        failed.iter().map(|s| s.as_str()).collect::<Vec<_>>().join("\n"));
}

/// Whether the case has a generated block that isn't a skip (even an empty
/// `states = []`: a real result a failure mustn't overwrite).
fn case_had_states(text: &str) -> bool {
    toml::from_str::<Case>(text).ok().and_then(|c| c.oracle).is_some_and(|o| o.skipped.is_none())
}

fn gen_one(name: &str, src: &str, text: &str) -> String {
    let head = text.split(GEN_MARK).next().unwrap_or(text).trim_end().to_owned();
    let case: Case = match toml::from_str(&head) {
        Ok(c) => c,
        Err(e) => return format!("hand-written part doesn't parse: {e}"),
    };
    let tc = toolchain();
    let mut block = format!("{GEN_MARK}\n[oracle]\ntoolchain = {:?}\nsource_hash = {:?}\n", tc, source_hash(src, &case.places, &tc));
    let mut note = String::new();
    match common::oracle::derive_states(src, &case.places) {
        Ok(states) => {
            block.push_str("states = [\n");
            for d in &states {
                let _ = writeln!(block, "  \"{} {} {} {}\",", d.func, d.line, d.place, d.is);
            }
            block.push_str("]\n");
            let _ = write!(note, "{} states", states.len());
            // Hand-written states rustc contradicts.
            for s in &case.state {
                let f = s.func.clone().unwrap_or_else(|| case.func.clone());
                if let Some(d) = states.iter().find(|d| d.func == f && d.line == s.row && d.place == s.place) {
                    if !compatible(&s.is, d.is) {
                        let _ = write!(note, "; CONTRADICTED: row {} {} hand {} vs rustc {}", s.row, s.place, s.is, d.is);
                    }
                }
            }
        }
        Err(e) => {
            // A failure must not erase states generated before (a transient
            // rustc or probe failure): keep the old block and fail the run.
            if case_had_states(text) {
                return format!("FAILED, kept the previous block: {e}");
            }
            let _ = writeln!(block, "skipped = {e:?}");
            let _ = write!(note, "oracle skipped: {e}");
        }
    }
    let path = cases_dir().join(format!("{name}.expect.toml"));
    std::fs::write(&path, format!("{head}\n\n{block}")).unwrap();
    note
}

