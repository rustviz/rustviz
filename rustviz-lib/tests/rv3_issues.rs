/// An event pattern: `<kind> <place>[ -> <target>]`; `_` matches any.
struct Pat {
    kind: String,
    place: String,
    target: Option<String>,
}

impl Pat {
    fn parse(s: &str) -> Result<Pat, String> {
        let (head, target) = match s.split_once("->") {
            Some((h, t)) => (h.trim(), Some(t.trim().to_owned())),
            None => (s.trim(), None),
        };
        let mut w = head.split_whitespace();
        let (Some(kind), Some(place), None) = (w.next(), w.next(), w.next()) else {
            return Err(format!("event {s:?} isn't `<kind> <place>[ -> <target>]`"));
        };
        if !EVENT_KINDS.contains(&kind) {
            return Err(format!("event kind {kind:?} not in {EVENT_KINDS:?}"));
        }
        Ok(Pat { kind: kind.into(), place: place.into(), target })
    }

    fn matches(&self, f: &Value) -> bool {
        let s = |k: &str| f[k].as_str().unwrap_or("");
        let eq = |want: &str, got: &str| want == "_" || want == got;
        // A target is one of a set ("r|h": both hold the loan).
        let tgt = |got: &str| self.target.as_deref().is_none_or(|t| t == "_" || holder_set(got).iter().any(|g| g == t));
        let kind = norm_kind(s("kind"));
        match (self.kind.as_str(), s("ev")) {
            ("init", "Init") => f["reassign"] != Value::Bool(true) && eq(&self.place, s("path")),
            ("reassign", "Init") => f["reassign"] == Value::Bool(true) && eq(&self.place, s("path")),
            ("move", "Move") | ("copy", "Copy") => eq(&self.place, s("path")) && tgt(s("to")),
            ("borrow", "Borrow") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-shared", "Borrow") => kind == "shared" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-mut", "Borrow") => kind == "mut" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-unique", "Borrow") => kind == "unique" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("end", "BorrowEnd") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("repoint", "Repoint") => eq(&self.place, s("holder")),
            // A `Drop` with nothing to drop runs no destructor.
            ("drop", "Drop") => s("how") != "nothing_to_drop" && eq(&self.place, s("path")),
            ("scope-end", "ScopeEnd") => eq(&self.place, s("path")),
            ("tempdrop", "TempDrop") => self.place == "_" || s("what").contains(self.place.as_str()),
            _ => false,
        }
    }
}

/// The body named `func`: exactly (`main`, `A::run`), or the one body
/// whose path ends in `::func`; two such bodies (`A::run`, `B::run`) are
/// an error, never a guess.
fn body<'a>(facts: &'a [BodyF], func: &str) -> Result<&'a BodyF, String> {
    if let Some(b) = facts.iter().find(|b| b.func == func) {
        return Ok(b);
    }
    let suffix = format!("::{func}");
    let hits: Vec<&BodyF> = facts.iter().filter(|b| b.func.ends_with(&suffix)).collect();
    match hits[..] {
        [b] => Ok(b),
        [] => Err(format!("no body `{func}` in the dump")),
        _ => Err(format!("`{func}` names several bodies: {:?}", hits.iter().map(|b| &b.func).collect::<Vec<_>>())),
    }
}

/// The state after row `row`, as the producer gives it for that row. A
/// row without a state of its own has none here: carrying a textually
/// earlier row would take a state from another path (a loop body, a
/// sibling arm).
fn row_after(b: &BodyF, row: u32) -> Option<&RowF> {
    b.rows.get(&row).filter(|r| !r.state.is_empty())
}

/// The facts that happen on row `row`: the row's own, except drops the
/// dump marks as run only on an early exit elsewhere (their MIR span is
/// the scope's `}`), plus facts marked as run by an early exit on `row`
/// (`early_exit`) or shared with one (`also_on_exits`).
fn row_facts(b: &BodyF, row: u32) -> Vec<&Value> {
    let mut out = Vec::new();
    for (l, r) in &b.rows {
        for f in &r.facts {
            let exit = f["early_exit"].as_u64().map(|e| e as u32);
            let also = nums(&f["also_on_exits"]);
            if (*l == row && exit.is_none()) || exit == Some(row) || (*l != row && also.contains(&row)) {
                out.push(f);
            }
        }
    }
    out
}

/// Whether `src`'s row `r` holds only braces, `else`, `;` (no code).
fn brace_only(src: &[&str], r: u32) -> bool {
    src.get(r as usize - 1).is_some_and(|l| l.replace("else", "").chars().all(|c| c.is_whitespace() || "{}();".contains(c)))
}

/// Whether a `BorrowEnd` on (`row`, `to`) is the end `want` names.
fn end_fits(want: EndSpec, row: u32, to: u32, src: &[&str]) -> bool {
    match want {
        EndSpec::Row(r) => r == row,
        EndSpec::Edge([r, n]) => r == row && to > r && to <= n && (to..n).all(|k| brace_only(src, k)),
    }
}

/// Whether the dump's ends match `want` one to one (a multiset: two
/// edges ending on one row are two ends).
fn ends_match(want: &[EndSpec], got: &[(u32, u32)], src: &[&str]) -> bool {
    if want.len() != got.len() {
        return false;
    }
    let mut used = vec![false; got.len()];
    // Edges first: they are the more specific.
    let mut order: Vec<&EndSpec> = want.iter().collect();
    order.sort_by_key(|w| matches!(w, EndSpec::Row(_)));
    order.iter().all(|w| {
        let hit = (0..got.len()).find(|&i| !used[i] && end_fits(**w, got[i].0, got[i].1, src));
        hit.map(|i| used[i] = true).is_some()
    })
}

fn kind_ok(want: &Option<String>, got: &str) -> bool {
    match want.as_deref() {
        None => true,
        Some("exclusive") => got == "mut" || got == "unique",
        Some(k) => k == got,
    }
}

/// Ok(()) or what the facts say instead. `src`: the program's lines.
fn check(a: &Assertion, facts: &[BodyF], src: &[&str]) -> Result<(), String> {
    let b = body(facts, &a.func)?;
    match &a.check {
        Check::State { row, place, is } => {
            let r = row_after(b, *row);
            let st = r.and_then(|r| r.state.get(place)).map(String::as_str);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            let parts = r.and_then(|r| r.parts.get(place));
            let any_parts = parts.is_some_and(|(m, may)| !m.is_empty() || !may.is_empty());
            let excl = lent.iter().any(|l| l.kind == "mut" || l.kind == "unique");
            // "maybe" alone doesn't say why: moved on some path (a move of
            // it, or of a parent, somewhere in the body) or never assigned
            // on some path (no such move). A producer may also say so.
            let was_moved = b.moved.iter().any(|m| m == place || place.starts_with(&format!("{m}.")));
            let ok = match is.as_str() {
                "own" => st == Some("own") && lent.is_empty() && !any_parts,
                "shared" => st == Some("own") && !lent.is_empty() && !excl,
                "mut" => matches!(st, Some("own" | "partly")) && excl,
                "moved" => st == Some("moved"),
                "maybe-moved" => st == Some("maybe-moved") || (st == Some("maybe") && was_moved),
                "moved*" => matches!(st, Some("moved" | "maybe" | "maybe-moved")),
                "partly" => st == Some("partly"),
                "partly*" => st == Some("partly") || any_parts,
                "unassigned" => st == Some("unassigned"),
                "maybe-unassigned" => st == Some("maybe-unassigned") || (st == Some("maybe") && !was_moved),
                "unassigned*" => matches!(st, Some("unassigned" | "maybe" | "maybe-unassigned")),
                "absent" => st.is_none(),
                _ => false,
            };
            let got = format!("{} lent {:?} parts {:?}", st.unwrap_or("(no state for this row)"),
                lent.iter().map(|l| format!("{}:L{}->{}", l.kind, l.loan, l.holders.join("|"))).collect::<Vec<_>>(), parts);
            if ok { Ok(()) } else { Err(got) }
        }
        Check::Lent { row, place, kind, holder, absent } => {
            let r = row_after(b, *row);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            if r.is_none() {
                return Err("(no state for this row)".into());
            }
            let hit = lent.iter().any(|l| kind_ok(kind, &l.kind) && holder.as_deref().is_none_or(|h| h == "_" || l.holders.iter().any(|x| x == h)));
            let got = format!("lent {:?}", lent.iter().map(|l| format!("{}:L{}->{}", l.kind, l.loan, l.holders.join("|"))).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Loan(l) => {
            let cands: Vec<&LoanF> = b.loans.iter()
                .filter(|x| x.line == l.row && x.lender == l.lender && kind_ok(&l.kind, &x.kind)
                    && l.holder.as_deref().is_none_or(|h| h == "_" || x.holders.iter().any(|y| y == h)))
                .collect();
            // Ends per CFG edge, from the dump's BorrowEnd facts: (row, next row).
            let edges = |x: &LoanF| -> Vec<(u32, u32)> { b.ends.iter().filter(|e| e.0 == x.id).map(|e| (e.1, e.2)).collect() };
            let fits = |x: &&LoanF| {
                let e = edges(x);
                l.ends.as_ref().is_none_or(|want| ends_match(want, &e, src))
                    && l.ends_include.iter().all(|r| e.iter().any(|g| g.0 == *r))
                    && !l.ends_exclude.iter().any(|r| e.iter().any(|g| g.0 == *r))
            };
            let hit = cands.iter().any(fits);
            let show = |x: &LoanF| format!("{} {} -> {:?} ends (row, next) {:?}", x.kind, x.lender, x.holders, edges(x));
            let got = if cands.is_empty() {
                format!("loans on row {}: {:?}", l.row, b.loans.iter().filter(|x| x.line == l.row).map(show).collect::<Vec<_>>())
            } else {
                format!("{:?}", cands.iter().map(|x| show(x)).collect::<Vec<_>>())
            };
            if l.absent { if cands.is_empty() { Ok(()) } else { Err(got) } } else if hit { Ok(()) } else { Err(got) }
        }
        Check::Drop { row, place, how, absent } => {
            let fs = row_facts(b, *row);
            let drops: Vec<&&Value> = fs.iter().filter(|f| {
                let ev = f["ev"].as_str().unwrap_or("");
                (ev == "Drop" || ev == "ScopeEnd") && f["path"].as_str() == Some(place.as_str())
            }).collect();
            let hit = drops.iter().any(|f| {
                let h = f["how"].as_str().unwrap_or("");
                let scope_end = f["ev"] == "ScopeEnd";
                match how.as_str() {
                    "definite" => h == "drops",
                    "conditional" => h == "drops_if_init",
                    "rest" => h == "drops_rest",
                    "none" => scope_end || h == "nothing_to_drop",
                    _ => !scope_end && h != "nothing_to_drop",
                }
            });
            let got = format!("{:?}", drops.iter().map(|f| f.to_string()).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Event { row, ev, absent } => {
            let p = Pat::parse(ev)?;
            let fs = row_facts(b, *row);
            let hit = fs.iter().any(|f| p.matches(f));
            if hit != *absent { Ok(()) } else { Err(format!("row facts: {}", brief(&fs))) }
        }
        Check::Order { row, events } => {
            let pats: Vec<Pat> = events.iter().map(|e| Pat::parse(e)).collect::<Result<_, _>>()?;
            let fs = row_facts(b, *row);
            let mut k = 0;
            for f in &fs {
                if k < pats.len() && pats[k].matches(f) {
                    k += 1;
                }
            }
            if k == pats.len() { Ok(()) } else { Err(format!("row facts in order: {}", brief(&fs))) }
        }
    }
}

fn brief(fs: &[&Value]) -> String {
    fs.iter().map(|f| {
        let s = |k: &str| f[k].as_str().unwrap_or("").to_owned();
        match s("ev").as_str() {
            "Move" | "Copy" => format!("{} {} -> {}", s("ev").to_lowercase(), s("path"), s("to")),
            "Borrow" => format!("borrow {} {} -> {}", s("kind"), s("lender"), s("holder")),
            "BorrowEnd" => format!("end {} -> {}", s("lender"), s("holder")),
            "Init" => format!("init {}", s("path")),
            "Drop" => format!("drop {} [{}]", s("path"), s("how")),
            "Repoint" => format!("repoint {}", s("holder")),
            e => format!("{} {}", e, s("path")),
        }
    }).collect::<Vec<_>>().join("; ")
}

#[test]
fn rv3_issue_cases_against_facts() {
    let all = cases();
    let strict = std::env::var("RV3_ISSUES_STRICT").is_ok_and(|v| v == "1");
    let jobs: usize = std::env::var("RV3_JOBS").ok().and_then(|v| v.parse().ok()).unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let results = std::sync::Mutex::new(Vec::new());
    std::thread::scope(|sc| {
        for _ in 0..jobs {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some((name, src, text)) = all.get(i) else { break };
                let case: Case = match toml::from_str(text) {
                    Ok(c) => c,
                    Err(e) => {
                        results.lock().unwrap().push((name.clone(), None, Err(format!("parse: {e}"))));
                        continue;
                    }
                };
                let dir = std::env::var("RV3_FACTS_DIR").ok();
                let r = facts_of(dir.as_deref(), name, src).and_then(|v| v.map(|v| load_facts(&v)).transpose());
                results.lock().unwrap().push((name.clone(), Some(case), r));
            });
        }
    });
    let mut results = results.into_inner().unwrap();
    results.sort_by(|a, b| a.0.cmp(&b.0));
    if results.is_empty() || results.iter().all(|(_, _, r)| matches!(r, Ok(None))) {
        let why = if results.is_empty() { "no cases (RV3_ISSUES_ONLY / RV3_JOBS?)" } else { "the installed plugin writes no RV3_FACTS dump (no fact layer)" };
        assert!(!strict, "RV3_ISSUES_STRICT=1 but no facts were checked: {why}");
        eprintln!("rv3_issue_cases_against_facts: skipped: {why}");
        return;
    }
    let mut report = String::new();
    let (mut pass, mut total) = (0, 0);
    let (mut a_pass, mut a_total) = (BTreeMap::<String, (usize, usize)>::new(), 0);
    let mut by_phase: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    let mut unexpected = Vec::new();
    let mut checked = 0;
    for (name, case, r) in &results {
        total += 1;
        let Some(case) = case else {
            let _ = writeln!(report, "FAIL {name}: {}", r.as_ref().err().unwrap());
            unexpected.push(name.clone());
            continue;
        };
        // No facts for a case (a plugin failure, an unreadable or missing
        // dump) checks nothing: never an expected failure.
        let facts = match r {
            Ok(Some(f)) => f,
            Ok(None) => {
                let _ = writeln!(report, "FAIL {name}: no fact dump (while other cases have one)");
                unexpected.push(format!("{name} (no dump)"));
                continue;
            }
            Err(e) => {
                let _ = writeln!(report, "FAIL {name}: {e}");
                unexpected.push(format!("{name} (no facts read)"));
                continue;
            }
        };
        checked += 1;
        let src = all.iter().find(|c| &c.0 == name).map(|c| c.1.as_str()).unwrap_or("");
        let src_lines: Vec<&str> = src.lines().collect();
        let mut fails = Vec::new();
        for a in assertions(case) {
            a_total += 1;
            let e = a_pass.entry(a.src.clone()).or_default();
            e.1 += 1;
            match check(&a, facts, &src_lines) {
                Ok(()) => e.0 += 1,
                Err(got) => fails.push(format!("    [{}] {}: got {}", a.src, a.what, got)),
            }
        }
        let ok = fails.is_empty();
        let phase = case.xfail.clone().unwrap_or_else(|| "-".into());
        let ph = by_phase.entry(phase.clone()).or_default();
        ph.1 += 1;
        if ok {
            pass += 1;
            ph.0 += 1;
        }
        let tag = match (ok, &case.xfail) {
            (true, None) => "pass",
            (true, Some(_)) => {
                unexpected.push(format!("{name} (passes: remove xfail)"));
                "PASS (xfail)"
            }
            (false, Some(_)) => "xfail",
            (false, None) => {
                unexpected.push(name.clone());
                "FAIL"
            }
        };
        let _ = writeln!(report, "{tag} {name} (#{}, {}, xfail {phase})", case.issue, case.cluster);
        for f in fails {
            let _ = writeln!(report, "{f}");
        }
    }
    let _ = writeln!(report, "\n{pass} of {total} issue tests pass");
    for (src, (p, t)) in &a_pass {
        let _ = writeln!(report, "  {src} assertions: {p} of {t} hold");
    }
    let _ = writeln!(report, "  ({a_total} assertions)");
    for (ph, (p, t)) in &by_phase {
        let _ = writeln!(report, "  xfail {ph}: {p} of {t} pass");
    }
    if let Ok(out) = std::env::var("RV3_ISSUES_REPORT") {
        std::fs::write(&out, &report).unwrap();
    }
    eprintln!("{report}");
    if strict {
        assert!(checked > 0, "RV3_ISSUES_STRICT=1 but no case's facts were read");
        assert!(unexpected.is_empty(), "RV3 issue tests: unexpected results:\n  {}", unexpected.join("\n  "));
    }
}

