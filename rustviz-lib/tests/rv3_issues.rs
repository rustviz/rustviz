/// Whether a hand-written state agrees with rustc's.
fn compatible(hand: &str, rustc: &str) -> bool {
    hand == rustc
        || matches!((hand, rustc), ("moved" | "maybe-moved", "moved*") | ("partly", "partly*") | ("unassigned" | "maybe-unassigned" | "maybe-moved" | "moved", "unassigned*"))
}

#[test]
fn rv3_issue_cases_gen() {
    if std::env::var("RV3_ISSUES_GEN").ok().as_deref() != Some("1") {
        return;
    }
    let all = cases();
    let jobs: usize = std::env::var("RV3_JOBS").ok().and_then(|v| v.parse().ok()).unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let notes = std::sync::Mutex::new(Vec::new());
    std::thread::scope(|sc| {
        for _ in 0..jobs {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some((name, src, text)) = all.get(i) else { break };
                let note = gen_one(name, src, text);
                notes.lock().unwrap().push(format!("{name}: {note}"));
            });
        }
    });
    let mut notes = notes.into_inner().unwrap();
    notes.sort();
    eprintln!("{}", notes.join("\n"));
}

fn gen_one(name: &str, src: &str, text: &str) -> String {
    let head = text.split(GEN_MARK).next().unwrap_or(text).trim_end().to_owned();
    let case: Case = match toml::from_str(&head) {
        Ok(c) => c,
        Err(e) => return format!("hand-written part doesn't parse: {e}"),
    };
    let mut block = format!("{GEN_MARK}\n[oracle]\ntoolchain = {:?}\nsource_hash = {:?}\n", toolchain(), source_hash(src));
    let mut note = String::new();
    match common::oracle::derive_states(src, &case.places) {
        Ok(states) => {
            block.push_str("states = [\n");
            for d in &states {
                let _ = writeln!(block, "  \"{} {} {} {}\",", d.func, d.line, d.place, d.is);
            }
            block.push_str("]\n");
            let _ = write!(note, "{} states", states.len());
            // Hand-written states rustc contradicts.
            for s in &case.state {
                let f = s.func.clone().unwrap_or_else(|| case.func.clone());
                if let Some(d) = states.iter().find(|d| d.func == f && d.line == s.row && d.place == s.place) {
                    if !compatible(&s.is, d.is) {
                        let _ = write!(note, "; CONTRADICTED: row {} {} hand {} vs rustc {}", s.row, s.place, s.is, d.is);
                    }
                }
            }
        }
        Err(e) => {
            let _ = writeln!(block, "skipped = {e:?}");
            let _ = write!(note, "oracle skipped: {e}");
        }
    }
    let path = cases_dir().join(format!("{name}.expect.toml"));
    std::fs::write(&path, format!("{head}\n\n{block}")).unwrap();
    note
}

/// The checker itself: facts with 2.x's #1675 mistake (x still lent to c
/// after the re-point, one end) fail the case's hand-written assertions;
/// the right facts pass them. Both dumps are in the RustViz 3 (v1) shape.
#[test]
fn rv3_harness_catches_wrong_facts() {
    let text = std::fs::read_to_string(cases_dir().join("1675_repoint_in_arm.expect.toml")).unwrap();
    let case: Case = toml::from_str(&text).unwrap();
    let dump = |l0_ends: &str, x6: &str| -> Vec<BodyF> {
        let v: Value = serde_json::from_str(&format!(r#"{{"version": 1, "bodies": [{{"func": "main",
            "loans": [{{"line": 4, "lender": "x", "kind": "shared", "holders": ["c"], "end_lines": {l0_ends}}},
                      {{"line": 6, "lender": "y", "kind": "shared", "holders": ["c"], "end_lines": [9]}}],
            "rows": [
              {{"line": 6, "state": {{"x": "own", "y": "own", "c": "own"}}, "lent": {{"x": {x6}, "y": [{{"loan": 2, "kind": "shared", "holder": "c"}}]}}, "facts": []}},
              {{"line": 8, "state": {{"x": "own", "y": "own", "c": "own"}}, "lent": {{"x": [{{"loan": 0, "kind": "shared", "holder": "c"}}]}}, "facts": []}}
            ]}}]}}"#)).unwrap();
        load_facts(&v).unwrap()
    };
    let issue: Vec<Assertion> = assertions(&case).into_iter().filter(|a| a.src == "issue").collect();
    let failing = |f: &[BodyF]| issue.iter().filter(|a| check(a, f).is_err()).map(|a| a.what.clone()).collect::<Vec<_>>();
    let right = dump("[5, 9]", "[]");
    // Row 7 has no row of its own in this dump: it carries row 6's state.
    assert!(failing(&right).is_empty(), "right facts fail: {:?}", failing(&right));
    let wrong = dump("[9]", r#"[{"loan": 0, "kind": "shared", "holder": "c"}]"#);
    let f = failing(&wrong);
    assert!(f.iter().any(|w| w.starts_with("loan of x on row 4")), "{f:?}");
    assert!(f.iter().any(|w| w == "after row 6: x is own"), "{f:?}");
    assert!(f.iter().any(|w| w == "after row 7: x is own"), "{f:?}");
}
