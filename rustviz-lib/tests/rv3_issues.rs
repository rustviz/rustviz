const STATES: &[&str] = &[
    "own", "shared", "mut", "moved", "maybe-moved", "moved*", "partly", "partly*", "unassigned", "maybe-unassigned",
    "unassigned*", "absent",
];
const PHASES: &[&str] = &["P0", "P1", "P2", "P3", "P4"];
const DROP_HOW: &[&str] = &["definite", "conditional", "rest", "none", "any"];
const EVENT_KINDS: &[&str] = &[
    "init", "reassign", "move", "copy", "borrow", "borrow-shared", "borrow-mut", "borrow-unique", "end", "repoint", "drop",
    "tempdrop", "scope-end",
];
const GEN_MARK: &str = "# ---- generated by RV3_ISSUES_GEN=1 (rustc probes); do not edit below ----";

#[derive(Deserialize, Debug, Default, Clone)]
#[serde(deny_unknown_fields)]
struct KnownCrash {
    issue: u32,
    /// A substring of the plugin's stderr naming the panic (`data.rs:5179`).
    panic_at: String,
    /// The phase whose work replaces the crashing code.
    phase: String,
}

#[derive(Deserialize, Debug, Default)]
#[serde(deny_unknown_fields)]
struct Case {
    issue: u32,
    cluster: String,
    title: String,
    /// The function the hand-written rows belong to.
    #[serde(default = "main_fn", rename = "fn")]
    func: String,
    /// Field paths the oracle should probe besides the variables.
    #[serde(default)]
    places: Vec<String>,
    /// RustViz 3 doesn't pass this yet: the PLAN.md phase that should.
    xfail: Option<String>,
    /// The plugin as a whole panics on this program (a drawing-path crash)
    /// but the fact layer still writes its dump. Strict mode passes the
    /// case only if the plugin fails with `panic_at` in its stderr AND the
    /// dump satisfies the assertions; if the crash stops, it fails so the
    /// marker gets removed. Never covers a missing or unreadable dump.
    #[serde(default)]
    known_crash: Option<KnownCrash>,
    #[serde(default)]
    duplicate_of: Option<u32>,
    #[serde(default)]
    note: Option<String>,
    /// What the issue is about that facts can't show (an arrow's route,
    /// a word), and the phase that owns it: "P3: the join dot".
    #[serde(default)]
    beyond_facts: Option<String>,
    #[serde(default)]
    state: Vec<StateA>,
    #[serde(default)]
    lent: Vec<LentA>,
    #[serde(default)]
    loan: Vec<LoanA>,
    #[serde(default)]
    drop: Vec<DropA>,
    #[serde(default)]
    event: Vec<EventA>,
    #[serde(default)]
    order: Vec<OrderA>,
    /// Generated states not to check, with the reason (rustc's verdict
    /// isn't what the program does: an unreachable or-pattern alternative).
    #[serde(default)]
    oracle_skip: Vec<OracleSkip>,
    oracle: Option<OracleBlock>,
}

