const STATES: &[&str] = &[
    "own", "shared", "mut", "moved", "maybe-moved", "maybe-imaginary", "moved*", "partly", "partly*", "unassigned",
    "maybe-unassigned", "unassigned*", "absent",
];
const PHASES: &[&str] = &["P0", "P1", "P2", "P3", "P4"];
const DROP_HOW: &[&str] = &["definite", "conditional", "rest", "none", "any"];
const EVENT_KINDS: &[&str] = &[
    "init", "reassign", "move", "copy", "borrow", "borrow-shared", "borrow-mut", "borrow-unique", "end", "repoint", "drop",
    "tempdrop", "scope-end",
];
const GEN_MARK: &str = "# ---- generated by RV3_ISSUES_GEN=1 (rustc probes); do not edit below ----";

#[derive(Deserialize, Debug, Default, Clone)]
#[serde(deny_unknown_fields)]
struct KnownCrash {
    issue: u32,
    /// A substring of the plugin's stderr naming the panic (`data.rs:5179`).
    panic_at: String,
    /// The phase whose work replaces the crashing code.
    phase: String,
}

#[derive(Deserialize, Debug, Default)]
#[serde(deny_unknown_fields)]
struct Case {
    issue: u32,
    cluster: String,
    title: String,
    /// The function the hand-written rows belong to.
    #[serde(default = "main_fn", rename = "fn")]
    func: String,
    /// Field paths the oracle should probe besides the variables.
    #[serde(default)]
    places: Vec<String>,
    /// Additional reviewed statement boundaries in nested expression blocks.
    #[serde(default)]
    probe: Vec<common::oracle::IssueProbe>,
    /// RustViz 3 doesn't pass this yet: the PLAN.md phase that should.
    xfail: Option<String>,
    /// The plugin as a whole panics on this program (a drawing-path crash)
    /// but the fact layer still writes its dump. Strict mode passes the
    /// case only if the plugin fails with `panic_at` in its stderr AND the
    /// dump satisfies the assertions; if the crash stops, it fails so the
    /// marker gets removed. Never covers a missing or unreadable dump.
    #[serde(default)]
    known_crash: Option<KnownCrash>,
    #[serde(default)]
    duplicate_of: Option<u32>,
    #[serde(default)]
    note: Option<String>,
    /// What the issue is about that facts can't show (an arrow's route,
    /// a word), and the phase that owns it: "P3: the join dot".
    #[serde(default)]
    beyond_facts: Option<String>,
    #[serde(default)]
    state: Vec<StateA>,
    #[serde(default)]
    lent: Vec<LentA>,
    #[serde(default)]
    loan: Vec<LoanA>,
    #[serde(default)]
    drop: Vec<DropA>,
    #[serde(default)]
    event: Vec<EventA>,
    #[serde(default)]
    order: Vec<OrderA>,
    /// Generated states not to check, with the reason (rustc's verdict
    /// isn't what the program does: an unreachable or-pattern alternative).
    #[serde(default)]
    oracle_skip: Vec<OracleSkip>,
    oracle: Option<OracleBlock>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct OracleSkip {
    /// None: every row.
    row: Option<u32>,
    place: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    why: String,
}

fn main_fn() -> String {
    "main".into()
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct StateA {
    row: u32,
    place: String,
    is: String,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct LentA {
    row: u32,
    /// A column (`a`, `p.x`), as the dump keys `lent`.
    place: String,
    kind: Option<String>,
    holder: Option<String>,
    /// The loan's borrowed place (`*a` for a reborrow through a).
    lender: Option<String>,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct LoanA {
    /// The row the borrow is taken on.
    row: u32,
    lender: String,
    kind: Option<String>,
    holder: Option<String>,
    /// Exactly these ends, one per CFG edge where the loan goes out of
    /// scope: `9` (an end on row 9, on any edge) or `[5, 6]` (an end on
    /// row 5 on the path that next runs row 6; arm entries
    /// and join braces are distinct targets).
    ends: Option<Vec<EndSpec>>,
    #[serde(default)]
    ends_include: Vec<u32>,
    #[serde(default)]
    ends_exclude: Vec<u32>,
    /// The source column (1-based) the dump records for the borrow: where
    /// it takes effect on its row (it places the loan in a one-line arm).
    #[serde(default)]
    col: Option<u32>,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct DropA {
    row: u32,
    place: String,
    #[serde(default = "any_how")]
    how: String,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone, Copy, PartialEq)]
#[serde(untagged)]
enum EndSpec {
    Row(u32),
    Edge([u32; 2]),
    /// `[row, next, col]`: also the column the path continues at (two ends
    /// on one row pair with different columns are two ends).
    EdgeCol([u32; 3]),
}

impl EndSpec {
    fn row(self) -> u32 {
        match self {
            EndSpec::Row(r) | EndSpec::Edge([r, _]) | EndSpec::EdgeCol([r, _, _]) => r,
        }
    }
}

fn any_how() -> String {
    "any".into()
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct EventA {
    row: u32,
    ev: String,
    #[serde(default)]
    absent: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone)]
#[serde(deny_unknown_fields)]
struct OrderA {
    row: u32,
    events: Vec<String>,
    /// The path runs no destructor the order does not name (stops a dump
    /// that drops both locals on a path where one moved).
    #[serde(default)]
    exact_drops: bool,
    src: String,
    #[serde(default, rename = "fn")]
    func: Option<String>,
    #[serde(default)]
    why: Option<String>,
}

#[derive(Deserialize, Debug, Clone, Default)]
#[serde(deny_unknown_fields)]
struct OracleBlock {
    toolchain: String,
    source_hash: String,
    /// "<fn> <row> <place> <state>", one per decided pair.
    #[serde(default)]
    states: Vec<String>,
    /// Why the oracle gave nothing, if it couldn't run.
    #[serde(default)]
    skipped: Option<String>,
}

fn cases_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("../rustviz-plugin/tests/rv3_issues")
}

/// (name, program, expect.toml text) of every case, sorted, narrowed by
/// `RV3_ISSUES_ONLY`.
fn cases() -> Vec<(String, String, String)> {
    let dir = cases_dir();
    let mut out = Vec::new();
    for e in std::fs::read_dir(&dir).unwrap_or_else(|e| panic!("read {dir:?}: {e}")) {
        let p = e.unwrap().path();
        let Some(name) = p.file_name().and_then(|n| n.to_str()).and_then(|n| n.strip_suffix(".expect.toml")) else { continue };
        let rs = dir.join(format!("{name}.rs"));
        let src = std::fs::read_to_string(&rs).unwrap_or_else(|e| panic!("{name}: no {rs:?}: {e}"));
        out.push((name.to_owned(), src, std::fs::read_to_string(&p).unwrap()));
    }
    if let Ok(only) = std::env::var("RV3_ISSUES_ONLY") {
        let pre: Vec<&str> = only.split(',').filter(|p| !p.is_empty()).collect();
        out.retain(|(n, _, _)| pre.iter().any(|p| n.starts_with(p)));
    }
    out.sort();
    out
}

/// FNV-1a 64 of what the oracle block is derived from (the program, the
/// extra places and probe sites, the toolchain): stable across Rust versions.
fn source_hash(src: &str, case: &Case, toolchain: &str) -> String {
    // Rustc treats CRLF as LF, so Windows checkouts share the same hash.
    let src = src.replace("\r\n", "\n");
    let mut h: u64 = 0xcbf29ce484222325;
    let mut inputs = case.places.join(",");
    for p in &case.probe {
        let _ = write!(inputs, "\0{} {} {}", p.func, p.row, p.place);
    }
    for b in src.bytes().chain([0]).chain(inputs.bytes()).chain([0]).chain(toolchain.bytes()) {
        h ^= b as u64;
        h = h.wrapping_mul(0x100000001b3);
    }
    format!("{h:016x}")
}

fn toolchain() -> String {
    rustviz_lib::toolchain_channel().to_owned()
}

/// Every assertion of a case, flattened: (src, fn, description, check).
enum Check {
    State { row: u32, place: String, is: String },
    Lent { row: u32, place: String, kind: Option<String>, holder: Option<String>, lender: Option<String>, absent: bool },
    Loan(LoanA),
    Drop { row: u32, place: String, how: String, absent: bool },
    Event { row: u32, ev: String, absent: bool },
    Order { row: u32, events: Vec<String>, exact_drops: bool },
}

struct Assertion {
    src: String,
    func: String,
    what: String,
    check: Check,
}

fn assertions(c: &Case) -> Vec<Assertion> {
    let f = |o: &Option<String>| o.clone().unwrap_or_else(|| c.func.clone());
    let mut out = Vec::new();
    for s in &c.state {
        out.push(Assertion { src: s.src.clone(), func: f(&s.func), what: format!("after row {}: {} is {}", s.row, s.place, s.is),
            check: Check::State { row: s.row, place: s.place.clone(), is: s.is.clone() } });
    }
    for l in &c.lent {
        out.push(Assertion {
            src: l.src.clone(),
            func: f(&l.func),
            what: format!("after row {}: {} {}lent{}{}", l.row, l.place, if l.absent { "not " } else { "" },
                l.kind.as_ref().map_or(String::new(), |k| format!(" {k}")), l.holder.as_ref().map_or(String::new(), |h| format!(" to {h}"))),
            check: Check::Lent { row: l.row, place: l.place.clone(), kind: l.kind.clone(), holder: l.holder.clone(), lender: l.lender.clone(), absent: l.absent },
        });
    }
    for l in &c.loan {
        out.push(Assertion {
            src: l.src.clone(),
            func: f(&l.func),
            what: format!("{}loan of {} on row {}{}{}{}", if l.absent { "no " } else { "" }, l.lender, l.row,
                l.holder.as_ref().map_or(String::new(), |h| format!(" to {h}")),
                l.ends.as_ref().map_or(String::new(), |e| format!(", ends {e:?}")),
                if l.ends_include.is_empty() && l.ends_exclude.is_empty() { String::new() } else { format!(", ends incl {:?} excl {:?}", l.ends_include, l.ends_exclude) }),
            check: Check::Loan(l.clone()),
        });
    }
    for d in &c.drop {
        out.push(Assertion { src: d.src.clone(), func: f(&d.func), what: format!("{}drop ({}) of {} on row {}", if d.absent { "no " } else { "" }, d.how, d.place, d.row),
            check: Check::Drop { row: d.row, place: d.place.clone(), how: d.how.clone(), absent: d.absent } });
    }
    for e in &c.event {
        out.push(Assertion { src: e.src.clone(), func: f(&e.func), what: format!("{}`{}` on row {}", if e.absent { "no " } else { "" }, e.ev, e.row),
            check: Check::Event { row: e.row, ev: e.ev.clone(), absent: e.absent } });
    }
    for o in &c.order {
        out.push(Assertion { src: o.src.clone(), func: f(&o.func), what: format!("on row {}, in order: {:?}", o.row, o.events),
            check: Check::Order { row: o.row, events: o.events.clone(), exact_drops: o.exact_drops } });
    }
    for s in c.oracle.iter().flat_map(|o| &o.states) {
        if let Ok((func, row, place, is)) = oracle_entry(s) {
            if skipped_by(c, &func, row, &place).is_some() {
                continue;
            }
            out.push(Assertion { src: "oracle".into(), func, what: format!("after row {row}: {place} is {is}"),
                check: Check::State { row, place, is } });
        }
    }
    out
}

/// The `oracle_skip` entry that leaves a generated state unchecked.
fn skipped_by<'a>(c: &'a Case, func: &str, row: u32, place: &str) -> Option<&'a OracleSkip> {
    c.oracle_skip.iter().find(|k| {
        k.place == place && k.row.is_none_or(|r| r == row) && k.func.as_deref().unwrap_or(c.func.as_str()) == func
    })
}

/// A generated state: "<fn> <row> <place> <state>".
fn oracle_entry(s: &str) -> Result<(String, u32, String, String), String> {
    // The fn name may hold spaces (`<D as Drop>::drop`): split from the right.
    let p: Vec<&str> = s.trim().rsplitn(4, ' ').collect();
    let [is, place, row, func] = p[..] else { return Err(format!("generated state {s:?} isn't `<fn> <row> <place> <state>`")) };
    if func.trim().is_empty() {
        return Err(format!("generated state {s:?} has no fn"));
    }
    let row = row.parse().map_err(|_| format!("generated state {s:?}: row isn't a number"))?;
    Ok((func.into(), row, place.into(), is.into()))
}

/// What's wrong with a case's text (empty: well formed).
fn problems(name: &str, src: &str, text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let c: Case = match toml::from_str(text) {
        Ok(c) => c,
        Err(e) => return vec![format!("doesn't parse: {e}")],
    };
    if !name.starts_with(&format!("{}_", c.issue)) {
        out.push(format!("file name doesn't start with its issue number {}_", c.issue));
    }
    if !c.cluster.starts_with('C') || c.title.is_empty() {
        out.push("cluster (Cnn) and title are required".into());
    }
    if let Some(x) = &c.xfail {
        if !PHASES.contains(&x.as_str()) {
            out.push(format!("xfail {x:?} is not one of {PHASES:?}"));
        }
    }
    if let Some(k) = &c.known_crash {
        if !PHASES.contains(&k.phase.as_str()) {
            out.push(format!("known_crash phase {:?} is not one of {PHASES:?}", k.phase));
        }
        if k.issue != c.issue {
            out.push(format!("known_crash issue {} is not the case's issue {}", k.issue, c.issue));
        }
        if k.panic_at.trim().is_empty() {
            out.push("known_crash needs a panic_at location substring".into());
        }
        if c.xfail.is_some() {
            out.push("known_crash and xfail are separate markers: use one".into());
        }
    }
    for (kind, row, why) in c.state.iter().map(|a| ("state", a.row, &a.why))
        .chain(c.lent.iter().map(|a| ("lent", a.row, &a.why)))
        .chain(c.loan.iter().map(|a| ("loan", a.row, &a.why)))
        .chain(c.drop.iter().map(|a| ("drop", a.row, &a.why)))
        .chain(c.event.iter().map(|a| ("event", a.row, &a.why)))
        .chain(c.order.iter().map(|a| ("order", a.row, &a.why)))
    {
        if why.as_deref().is_none_or(|w| w.trim().is_empty()) {
            out.push(format!("[[{kind}]] row {row}: give the rustc evidence in `why`"));
        }
    }
    let n_lines = src.lines().count() as u32;
    let rows: Vec<u32> = c.state.iter().map(|s| s.row).chain(c.lent.iter().map(|s| s.row)).chain(c.loan.iter().map(|s| s.row))
        .chain(c.loan.iter().flat_map(|l| l.ends.iter().flatten().flat_map(|e| match *e {
            EndSpec::Row(r) => vec![r],
            EndSpec::Edge([r, n]) | EndSpec::EdgeCol([r, n, _]) => vec![r, n],
        })))
        .chain(c.loan.iter().flat_map(|l| l.ends_include.iter().chain(&l.ends_exclude).copied()))
        .chain(c.oracle.iter().flat_map(|o| &o.states).filter_map(|s| oracle_entry(s).ok().map(|e| e.1)))
        .chain(c.drop.iter().map(|s| s.row)).chain(c.event.iter().map(|s| s.row)).chain(c.order.iter().map(|s| s.row)).collect();
    if let Some(r) = rows.iter().find(|&&r| r == 0 || r > n_lines) {
        out.push(format!("row {r} is not a line of the program (1..={n_lines})"));
    }
    for a in assertions(&c) {
        if a.src != "oracle" && a.src != "issue" {
            out.push(format!("{}: src must be \"oracle\" or \"issue\", not {:?}", a.what, a.src));
        }
        match &a.check {
            Check::State { is, .. } if !STATES.contains(&is.as_str()) => out.push(format!("{}: state {is:?} not in {STATES:?}", a.what)),
            Check::Lent { kind: Some(k), .. } if k == "reserved" => {}
            Check::Lent { kind: Some(k), .. } | Check::Loan(LoanA { kind: Some(k), .. }) if !["shared", "mut", "unique", "exclusive"].contains(&k.as_str()) => {
                out.push(format!("{}: kind {k:?} not shared|mut|unique|exclusive", a.what))
            }
            Check::Drop { how, .. } if !DROP_HOW.contains(&how.as_str()) => out.push(format!("{}: how {how:?} not in {DROP_HOW:?}", a.what)),
            Check::Event { ev, .. } => {
                if let Err(e) = Pat::parse(ev) {
                    out.push(format!("{}: {e}", a.what));
                }
            }
            Check::Order { events, .. } => {
                if events.len() < 2 {
                    out.push(format!("{}: an order needs two events or more", a.what));
                }
                for ev in events {
                    if let Err(e) = Pat::parse(ev) {
                        out.push(format!("{}: {e}", a.what));
                    }
                }
            }
            _ => {}
        }
    }
    if c.state.iter().any(|s| s.src == "oracle") {
        out.push("hand-written [[state]] with src = \"oracle\": put rustc-derived states in the generated block".into());
    }
    let generated: Vec<(String, u32, String)> = c.oracle.iter().flat_map(|o| &o.states)
        .filter_map(|e| oracle_entry(e).ok().map(|(f, r, p, _)| (f, r, p))).collect();
    for k in &c.oracle_skip {
        let f = k.func.clone().unwrap_or_else(|| c.func.clone());
        if !generated.iter().any(|(gf, gr, gp)| *gf == f && *gp == k.place && k.row.is_none_or(|r| r == *gr)) {
            out.push(format!("oracle_skip for {} (row {:?}) matches no generated state", k.place, k.row));
        }
    }
    match &c.oracle {
        None => out.push("no [oracle] block: run RV3_ISSUES_GEN=1".into()),
        Some(o) => {
            if o.source_hash != source_hash(src, &c, &o.toolchain) || o.toolchain != toolchain() {
                out.push("[oracle] is stale (the program, probe inputs or toolchain changed): run RV3_ISSUES_GEN=1".into());
            }
            for p in &c.probe {
                if !generated.contains(&(p.func.clone(), p.row, p.place.clone())) {
                    out.push(format!("missing generated verdict for probe {} {} {}", p.func, p.row, p.place));
                }
            }
            for e in &o.states {
                if let Err(m) = oracle_entry(e) {
                    out.push(m);
                }
            }
            if !text.contains(GEN_MARK) {
                out.push("the generated block lost its marker line".into());
            }
        }
    }
    let n_issue = assertions(&c).iter().filter(|a| a.src == "issue").count();
    if n_issue == 0 && c.duplicate_of.is_none() {
        out.push("no hand-written (src = \"issue\") assertion: what does the issue say is true?".into());
    }
    out
}

#[test]
fn rv3_issue_cases_well_formed() {
    let mut bad = String::new();
    let all = cases();
    for (name, src, text) in &all {
        for p in problems(name, src, text) {
            let _ = writeln!(bad, "{name}: {p}");
        }
    }
    assert!(bad.is_empty(), "malformed RV3 issue cases:\n{bad}");
    eprintln!("rv3_issue_cases_well_formed: {} cases", all.len());
}

#[test]
fn rv3_issue_case_freshness_accepts_crlf() {
    let name = "1675_repoint_in_arm";
    let dir = cases_dir();
    let crlf = |file: &str| {
        std::fs::read_to_string(dir.join(file))
            .unwrap()
            .replace("\r\n", "\n")
            .replace('\n', "\r\n")
    };
    let src = crlf("1675_repoint_in_arm.rs");
    let text = crlf("1675_repoint_in_arm.expect.toml");
    let fresh = problems(name, &src, &text);
    assert!(fresh.is_empty(), "CRLF checkout rejected: {fresh:?}");

    let edited = src.replace("let mut c = &x;", "let mut c = &y;");
    let stale = problems(name, &edited, &text);
    assert!(
        stale.iter().any(|p| p.starts_with("[oracle] is stale")),
        "edited program accepted: {stale:?}"
    );
}

// ─── Facts (adapter) ────────────────────────────────────────────────
//
// The harness reads the fact dump through this adapter, so the dump's
// shape can change without touching the cases. Two shapes are read:
// the RustViz 3 fact layer's (`{"version": 1, "bodies": [..]}`,
// `rustviz-plugin/src/facts/schema.rs`) and the spike's (a bare array of
// bodies whose `lent` is keyed by lender with "kind:L<n>->holder" strings,
// branch spike/rustviz3).

#[derive(Debug, Clone)]
struct Lent {
    loan: usize,
    /// Normalised row kind, or None for a legacy two-phase loan with no phase.
    kind: Option<String>,
    /// One loan can have several holders (a copied reference: "r|h").
    holders: Vec<String>,
}

#[derive(Debug, Clone, Default)]
struct RowF {
    state: BTreeMap<String, String>,
    /// column -> (fields moved on every path, fields moved on some paths)
    parts: BTreeMap<String, (Vec<String>, Vec<String>)>,
    lent: BTreeMap<String, Vec<Lent>>,
    /// column -> why it is "maybe" ("moved" | "unassigned" | "imaginary"),
    /// if the dump says.
    cause: BTreeMap<String, String>,
    facts: Vec<Value>,
    /// The row's arms (several arms of branches on one row): each one's
    /// branch and its parent arm, if nested.
    arms: Vec<(usize, Option<usize>)>,
}

#[derive(Debug, Clone)]
struct LoanF {
    id: usize,
    line: u32,
    col: Option<u32>,
    lender: String,
    kind: String,
    two_phase: bool,
    holders: Vec<String>,
    /// The loan record's end rows, when the dump gives them.
    end_lines: Option<Vec<u32>>,
    /// A loan of rustc's borrow set (v3 `source` "borrow" / "temporary"; every
    /// loan of an older dump). `[[loan]]` speaks about these only: a reference
    /// parameter's, a constant's or an untracked shared reborrow's loan isn't
    /// one rustc's borrow checker has.
    tracked: bool,
}

#[derive(Debug, Clone)]
struct BodyF {
    func: String,
    rows: BTreeMap<u32, RowF>,
    loans: Vec<LoanF>,
    /// (loan, row, the next row of that path) of every `BorrowEnd`.
    ends: Vec<(usize, u32, u32, u32)>,
    /// None for the spike, whose facts have no arm or loan-phase information.
    version: Option<u64>,
}

/// The producer's borrow kind, normalised: `mut(two-phase)` is mut, a
/// closure's `unique(..)` stays unique (not mut), `reserved` (a two-phase
/// `&mut` before its activation, v2) stays reserved.
fn norm_kind(k: &str) -> String {
    let k = k.trim().to_ascii_lowercase();
    for base in ["shared", "mut", "unique", "reserved", "shallow"] {
        if k.starts_with(base) {
            return base.into();
        }
    }
    k
}

/// "r|h" -> [r, h].
fn holder_set(s: &str) -> Vec<String> {
    s.split('|').map(str::trim).filter(|h| !h.is_empty()).map(str::to_owned).collect()
}

fn strs(v: &Value) -> Vec<String> {
    v.as_array().into_iter().flatten().filter_map(|x| x.as_str().map(str::to_owned)).collect()
}

fn nums(v: &Value) -> Vec<u32> {
    v.as_array().into_iter().flatten().filter_map(|x| x.as_u64().map(|n| n as u32)).collect()
}

/// Whether a loan of `lender` restricts column `col` (spike dumps only:
/// RustViz 3's are keyed by column already). One is a field path of the
/// other; `v[_]` restricts `v`. `*b` / `**r` restrict the root only when
/// every dereference goes through a Box or a `&mut` (`ty_of`: the root's
/// type); a loan of the referent of a shared reference leaves the
/// reference free (`&**r` with `r: &mut &String` doesn't restrict r).
fn overlaps(lender: &str, col: &str, ty_of: &dyn Fn(&str) -> Option<String>) -> bool {
    let derefs = lender.len() - lender.trim_start_matches('*').len();
    let l = lender.trim_start_matches('*');
    if derefs > 0 {
        let root = l.split(['.', '[']).next().unwrap_or(l);
        if !ty_of(root).is_some_and(|t| derefs_restrict(&t, derefs)) {
            return lender == col;
        }
    }
    let l = l.split('[').next().unwrap_or(l);
    l == col || l.starts_with(&format!("{col}.")) || col.starts_with(&format!("{l}."))
}

/// Whether dereferencing a value of type `ty` `n` times goes through `&mut`
/// or `Box` only (a loan there restricts the value itself).
fn derefs_restrict(ty: &str, n: usize) -> bool {
    let mut t = ty.trim().to_owned();
    for _ in 0..n {
        if let Some(rest) = t.strip_prefix('&') {
            let rest = rest.trim_start();
            // A lifetime: `&'a mut T`.
            let rest = if rest.starts_with('\'') { rest.split_once(' ').map_or("", |x| x.1) } else { rest };
            match rest.strip_prefix("mut ") {
                Some(inner) => t = inner.trim().to_owned(),
                None => return false,
            }
        } else if let Some(at) = t.find("Box<").filter(|&a| t[..a].chars().all(|c| c.is_alphanumeric() || c == ':' || c == '_')) {
            let inner = &t[at + 4..];
            let inner = inner.rsplit_once('>').map_or(inner, |x| x.0);
            // `Box<T, A>`: the first argument.
            t = inner.split(", std::alloc").next().unwrap_or(inner).trim().to_owned();
        } else {
            return false;
        }
    }
    true
}

/// Column names are the 2.x ones, which mark a variable that can't share a
/// column with a same-named one (the `iter` of a `for` desugaring) with
/// invisible `SCOPE_MARK`s (U+E000); cases name what is shown. A body's
/// marks are dropped only when that keeps its columns apart (two columns
/// that differ only by marks keep them, and a case can't name the marked
/// one).
fn unmark(v: &Value) -> Result<Value, String> {
    const MARK: char = '\u{E000}';
    let Some(bodies) = v.get("bodies").and_then(Value::as_array) else { return Ok(v.clone()) };
    let mut out = v.clone();
    for (k, b) in bodies.iter().enumerate() {
        let names: Vec<&str> = b["columns"].as_array().into_iter().flatten().filter_map(|c| c["name"].as_str())
            .chain(b["vars"].as_array().into_iter().flatten().filter_map(|c| c["name"].as_str()))
            .collect();
        let mut plain: Vec<String> = names.iter().map(|n| n.replace(MARK, "")).collect();
        let mut raw: Vec<&str> = names.clone();
        raw.sort();
        raw.dedup();
        plain.sort();
        plain.dedup();
        if plain.len() == raw.len() {
            out["bodies"][k] = serde_json::from_str(&b.to_string().replace(MARK, "")).map_err(|e| e.to_string())?;
        }
    }
    Ok(out)
}

fn load_facts(v: &Value) -> Result<Vec<BodyF>, String> {
    let unmarked = unmark(v)?;
    let v = &unmarked;
    let version = v.get("version").and_then(Value::as_u64);
    let (bodies, spike) = match v {
        Value::Array(a) => (a.clone(), true),
        Value::Object(o) => match (version, o.get("bodies")) {
            (Some(1 | 2 | 3), Some(Value::Array(b))) => {
                // A body the producer failed on has no facts: that's a
                // failure to read, never an expected (xfail) result.
                let errs = o.get("errors").map(strs).unwrap_or_default();
                if !errs.is_empty() {
                    return Err(format!("the fact producer failed: {errs:?}"));
                }
                // No body: nothing to check is a failure to read, too.
                if b.is_empty() {
                    return Err("the fact dump has no bodies".into());
                }
                (b.clone(), false)
            }
            (ver, _) => return Err(format!("fact dump version {ver:?}: teach load_facts this shape")),
        },
        _ => return Err("fact dump is neither an object nor an array".into()),
    };
    let mut out = Vec::new();
    for b in &bodies {
        // Variables' types (spike dumps: which `*x` loans restrict x).
        let types: Vec<(String, String)> = b["vars"].as_array().into_iter().flatten()
            .filter_map(|v| Some((v["name"].as_str()?.to_owned(), v["ty"].as_str()?.to_owned())))
            .collect();
        let ty_of = |root: &str| types.iter().find(|(n, _)| n == root).map(|(_, t)| t.clone());
        let mut rows = BTreeMap::new();
        for r in b["rows"].as_array().into_iter().flatten() {
            let line = r["line"].as_u64().unwrap_or(0) as u32;
            let state: BTreeMap<String, String> = r["state"].as_object().into_iter().flatten()
                .filter_map(|(k, s)| s.as_str().map(|s| (k.clone(), s.to_owned()))).collect();
            let mut lent: BTreeMap<String, Vec<Lent>> = BTreeMap::new();
            for (k, ls) in r["lent"].as_object().into_iter().flatten() {
                for l in ls.as_array().into_iter().flatten() {
                    if spike {
                        // "shared:L0->c"
                        let s = l.as_str().unwrap_or("");
                        let (kind, rest) = s.split_once(':').unwrap_or(("", s));
                        let (id, holder) = rest.split_once("->").unwrap_or((rest, ""));
                        let lt = Lent {
                            loan: id.trim_start_matches('L').parse().unwrap_or(usize::MAX),
                            kind: (kind != "mut(two-phase)").then(|| norm_kind(kind)),
                            holders: holder_set(holder),
                        };
                        let mut cols: Vec<String> = state.keys().filter(|c| overlaps(k, c, &ty_of)).cloned().collect();
                        cols.push(k.clone());
                        cols.sort();
                        cols.dedup();
                        for c in cols {
                            lent.entry(c).or_default().push(lt.clone());
                        }
                    } else {
                        lent.entry(k.clone()).or_default().push(Lent {
                            loan: l["loan"].as_u64().unwrap_or(u64::MAX) as usize,
                            // `mut(two-phase)` names the loan's kind, not its phase.
                            kind: l["kind"].as_str().filter(|k| *k != "mut(two-phase)").map(norm_kind),
                            holders: holder_set(l["holder"].as_str().unwrap_or("")),
                        });
                    }
                }
            }
            let parts = r["parts"].as_object().into_iter().flatten()
                .map(|(k, p)| (k.clone(), (strs(&p["moved"]), strs(&p["maybe"])))).collect();
            let facts = r["facts"].as_array().cloned().unwrap_or_default();
            let arms = r["arms"].as_array().into_iter().flatten()
                .map(|a| (a["branch"].as_u64().unwrap_or(0) as usize, a["parent"].as_u64().map(|p| p as usize))).collect();
            let cause = r["cause"].as_object().into_iter().flatten()
                .filter_map(|(k, c)| c.as_str().map(|c| (k.clone(), c.to_owned()))).collect();
            rows.insert(line, RowF { state, parts, lent, cause, facts, arms });
        }
        let loans: Vec<LoanF> = b["loans"].as_array().into_iter().flatten().map(|l| LoanF {
            id: l["loan"].as_u64().unwrap_or(u64::MAX) as usize,
            line: l["line"].as_u64().unwrap_or(0) as u32,
            col: l["col"].as_u64().map(|c| c as u32),
            lender: l["lender"].as_str().unwrap_or("").into(),
            kind: norm_kind(l["kind"].as_str().unwrap_or("")),
            two_phase: l["two_phase"] == true || l["kind"] == "mut(two-phase)",
            holders: strs(&l["holders"]).iter().flat_map(|h| holder_set(h)).collect(),
            end_lines: l.get("end_lines").map(nums),
            tracked: l.get("source").and_then(Value::as_str).is_none_or(|s| s == "borrow" || s == "temporary"),
        }).collect();
        // A spike row says `mut` for a closure's unique capture: its `lent`
        // entries take the kind from the loan's record. RustViz 3 rows
        // (v2 and v3: shared | mut | unique | reserved) are kept as they are, so a
        // row that contradicts its record is caught.
        if !matches!(version, Some(2 | 3)) {
            for r in rows.values_mut() {
                for ls in r.lent.values_mut() {
                    for lt in ls.iter_mut() {
                        if let Some(x) = loans.iter().find(|x| x.id == lt.loan) {
                            if x.two_phase {
                                lt.kind = None;
                            } else if x.kind == "unique" {
                                lt.kind = Some(x.kind.clone());
                            }
                        }
                    }
                }
            }
        }
        let mut ends = Vec::new();
        for (line, r) in &rows {
            for f in &r.facts {
                if f["ev"] == "BorrowEnd" {
                    ends.push((
                        f["loan"].as_u64().unwrap_or(u64::MAX) as usize,
                        *line,
                        f["to_line"].as_u64().map_or(0, |t| t as u32),
                        f["to_col"].as_u64().map_or(0, |t| t as u32),
                    ));
                }
            }
        }
        out.push(BodyF { func: b["func"].as_str().unwrap_or("").into(), rows, loans, ends, version });
    }
    Ok(out)
}

/// Whether the plugin's exit may be accepted. A failure is accepted only
/// for a `known_crash` whose `panic_at` is in stderr (the dump is then
/// still read and checked); a case that no longer crashes must drop the
/// marker.
fn crash_verdict(crash: Option<&KnownCrash>, ok: bool, stderr: &str) -> Result<(), String> {
    match (crash, ok) {
        (None, true) => Ok(()),
        (None, false) => Err(format!("cargo rv-plugin failed: {}", stderr.chars().take(600).collect::<String>())),
        (Some(k), true) => Err(format!("known_crash (#{}, {}) but the plugin no longer fails: remove known_crash", k.issue, k.panic_at)),
        (Some(k), false) if stderr.contains(&k.panic_at) => Ok(()),
        (Some(k), false) => Err(format!(
            "known_crash expects a panic at {:?} but the plugin failed differently: {}",
            k.panic_at,
            stderr.chars().take(600).collect::<String>()
        )),
    }
}

/// The fact dump of `src`: `<dir>/<name>.facts.json` when a dump
/// directory is given (`RV3_FACTS_DIR`; a missing directory or file is an
/// error), else from the installed plugin (`cargo rv-plugin` with
/// `RV3_FACTS`). Ok(None) only when the plugin ran and wrote no dump (a
/// build without the fact layer).
fn facts_of(dir: Option<&str>, name: &str, src: &str, crash: Option<&KnownCrash>) -> Result<Option<Value>, String> {
    if let Some(dir) = dir {
        if !Path::new(dir).is_dir() {
            return Err(format!("RV3_FACTS_DIR {dir:?} is not a directory"));
        }
        let p = Path::new(dir).join(format!("{name}.facts.json"));
        // issue-facts.sh keeps a failing plugin's stderr in `<name>.err`.
        let err = std::fs::read_to_string(Path::new(dir).join(format!("{name}.err"))).ok();
        if crash.is_some() {
            crash_verdict(crash, err.is_none(), err.as_deref().unwrap_or(""))?;
        }
        let t = std::fs::read_to_string(&p).map_err(|e| format!("no dump {p:?}: {e}"))?;
        return serde_json::from_str(&t).map(Some).map_err(|e| format!("{p:?}: {e}"));
    }
    let tmp = tempfile::tempdir().map_err(|e| e.to_string())?;
    let proj = tmp.path().join("user-code");
    std::fs::create_dir_all(proj.join("src")).map_err(|e| e.to_string())?;
    std::fs::write(proj.join("Cargo.toml"), "[package]\nname = \"user-code\"\nversion = \"0.1.0\"\nedition = \"2024\"\n").map_err(|e| e.to_string())?;
    std::fs::write(proj.join("rust-toolchain.toml"), include_str!("../../rust-toolchain.toml")).map_err(|e| e.to_string())?;
    std::fs::write(proj.join("src/lib.rs"), src).map_err(|e| e.to_string())?;
    let dump = tmp.path().join("facts.json");
    let out = Command::new("cargo")
        .arg("rv-plugin")
        .current_dir(&proj)
        .env("CARGO_TERM_COLOR", "never")
        .env("RV3_FACTS", &dump)
        .env_remove("CARGO_TARGET_DIR")
        .env_remove("CARGO_BUILD_TARGET_DIR")
        .output()
        .map_err(|e| format!("run cargo rv-plugin: {e}"))?;
    crash_verdict(crash, out.status.success(), &String::from_utf8_lossy(&out.stderr))?;
    match std::fs::read_to_string(&dump) {
        Ok(t) => {
            // `RV3_FACTS_SAVE=<dir>` keeps the dumps (for `RV3_FACTS_DIR`).
            if let Ok(save) = std::env::var("RV3_FACTS_SAVE") {
                let _ = std::fs::create_dir_all(&save);
                let _ = std::fs::write(Path::new(&save).join(format!("{name}.facts.json")), &t);
            }
            serde_json::from_str(&t).map(Some).map_err(|e| format!("fact dump: {e}"))
        }
        Err(_) => Ok(None),
    }
}

// ─── Checking ───────────────────────────────────────────────────────

/// An event pattern: `<kind> <place>[ -> <target>]`; `_` matches any.
struct Pat {
    kind: String,
    place: String,
    target: Option<String>,
}

impl Pat {
    fn parse(s: &str) -> Result<Pat, String> {
        let (head, target) = match s.split_once("->") {
            Some((h, t)) => (h.trim(), Some(t.trim().to_owned())),
            None => (s.trim(), None),
        };
        // (A place may have spaces: `(make_o().opt as Some).0`.)
        let Some((kind, place)) = head.split_once(char::is_whitespace).map(|(k, p)| (k, p.trim())).filter(|(_, p)| !p.is_empty()) else {
            return Err(format!("event {s:?} isn't `<kind> <place>[ -> <target>]`"));
        };
        if !EVENT_KINDS.contains(&kind) {
            return Err(format!("event kind {kind:?} not in {EVENT_KINDS:?}"));
        }
        Ok(Pat { kind: kind.into(), place: place.into(), target })
    }

    fn matches(&self, f: &Value) -> bool {
        let s = |k: &str| f[k].as_str().unwrap_or("");
        let eq = |want: &str, got: &str| want == "_" || want == got;
        // A target is one of a set ("r|h": both hold the loan).
        let tgt = |got: &str| self.target.as_deref().is_none_or(|t| t == "_" || holder_set(got).iter().any(|g| g == t));
        let kind = norm_kind(s("kind"));
        match (self.kind.as_str(), s("ev")) {
            ("init", "Init") => f["reassign"] != Value::Bool(true) && eq(&self.place, s("path")),
            ("reassign", "Init") => f["reassign"] == Value::Bool(true) && eq(&self.place, s("path")),
            ("move", "Move") | ("copy", "Copy") => eq(&self.place, s("path")) && tgt(s("to")),
            ("borrow", "Borrow") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-shared", "Borrow") => kind == "shared" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-mut", "Borrow") => kind == "mut" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("borrow-unique", "Borrow") => kind == "unique" && eq(&self.place, s("lender")) && tgt(s("holder")),
            ("end", "BorrowEnd") => eq(&self.place, s("lender")) && tgt(s("holder")),
            ("repoint", "Repoint") => eq(&self.place, s("holder")),
            // A `Drop` with nothing to drop runs no destructor.
            ("drop", "Drop") => s("how") != "nothing_to_drop" && eq(&self.place, s("path")),
            ("scope-end", "ScopeEnd") => eq(&self.place, s("path")),
            ("tempdrop", "TempDrop") => self.place == "_" || s("what").contains(self.place.as_str()),
            _ => false,
        }
    }
}

/// The body named `func`: exactly (`main`, `A::run`), or the one body
/// whose path ends in `::func`; two such bodies (`A::run`, `B::run`) are
/// an error, never a guess.
fn body<'a>(facts: &'a [BodyF], func: &str) -> Result<&'a BodyF, String> {
    if let Some(b) = facts.iter().find(|b| b.func == func) {
        return Ok(b);
    }
    let one = |hits: Vec<&'a BodyF>, how: &str| -> Option<Result<&'a BodyF, String>> {
        match hits[..] {
            [b] => Some(Ok(b)),
            [] => None,
            _ => Some(Err(format!("`{func}` names several bodies ({how}): {:?}", hits.iter().map(|b| &b.func).collect::<Vec<_>>()))),
        }
    };
    let c = canon_fn(func);
    if let Some(r) = one(facts.iter().filter(|b| canon_fn(&b.func) == c).collect(), "same canonical name") {
        return r;
    }
    let suffix = format!("::{c}");
    one(facts.iter().filter(|b| canon_fn(&b.func).ends_with(&suffix)).collect(), "same path suffix")
        .unwrap_or_else(|| Err(format!("no body `{func}` in the dump")))
}

/// A function path without generic arguments; in a qualified self type
/// the trait is shortened to its last segment, the type keeps its module
/// path: `<D<'_> as std::ops::Drop>::drop` -> `<D as Drop>::drop`,
/// `<a::D as Drop>::drop` stays apart from `<b::D as Drop>::drop`;
/// `a::Foo::<T>::bar` -> `a::Foo::bar`.
fn canon_fn(s: &str) -> String {
    // Drop `<..>` right after a name or `::` (generic arguments); keep a
    // leading `<` (a qualified self type).
    let mut out = String::new();
    let mut depth = 0usize;
    for c in s.chars() {
        if depth > 0 {
            match c {
                '<' => depth += 1,
                '>' => depth -= 1,
                _ => {}
            }
            continue;
        }
        if c == '<' && out.chars().last().is_some_and(|p| p.is_alphanumeric() || p == '_' || p == ':') {
            if out.ends_with("::") {
                out.truncate(out.len() - 2);
            }
            depth = 1;
            continue;
        }
        out.push(c);
    }
    if let Some(rest) = out.strip_prefix('<') {
        if let Some((inner, tail)) = rest.split_once('>') {
            let inner = match inner.split_once(" as ") {
                Some((ty, tr)) => format!("{} as {}", ty.trim(), tr.rsplit("::").next().unwrap_or(tr).trim()),
                None => inner.trim().to_owned(),
            };
            return format!("<{inner}>{tail}");
        }
    }
    out
}

/// The state after row `row`, as the producer gives it for that row. A
/// row without a state of its own has none here: carrying a textually
/// earlier row would take a state from another path (a loop body, a
/// sibling arm).
fn row_after(b: &BodyF, row: u32) -> Option<&RowF> {
    b.rows.get(&row).filter(|r| !r.state.is_empty())
}

/// Events with a position on a specific exit carry that exit row's arm.
/// Older dumps can identify a shared MIR drop only by `also_on_exits`.
/// Such a summary has no position in the exit's evaluation order.
#[derive(Default)]
struct RowFacts<'a> {
    located: Vec<&'a Value>,
    shared_drops: Vec<&'a Value>,
    /// A v3 producer gives every exit that drops a value its own positioned
    /// event (an exit whose value already moved has none), so a shared
    /// summary says nothing more about whether this exit drops.
    resolved: bool,
}

impl<'a> RowFacts<'a> {
    /// A definite drop at a shared site runs on every listed exit. A drop
    /// flag at that site does not say which exit actually drops the value.
    fn events(&self) -> impl Iterator<Item = &'a Value> + '_ {
        self.located.iter().copied().chain(self.shared_drops.iter().copied().filter(|f| f["how"] == "drops"))
    }

    fn may_drop(&self, place: &str) -> bool {
        !self.resolved && self.shared_drops.iter().any(|f| matches!(f["how"].as_str(), Some("drops_if_init" | "drops_rest"))
            && (place == "_" || f["path"] == place))
    }
}

fn row_facts(b: &BodyF, row: u32) -> RowFacts<'_> {
    let mut out = RowFacts { resolved: b.version == Some(3), ..Default::default() };
    for (l, r) in &b.rows {
        for f in &r.facts {
            let exit = f["early_exit"].as_u64().map(|e| e as u32);
            // The scope-end summary is not the exit's own drop, even when the
            // exit and the closing brace share a source row.
            let summary = f["ev"] == "Drop" && exit.is_none() && nums(&f["also_on_exits"]).contains(&row);
            if !summary && exit.unwrap_or(*l) == row {
                out.located.push(f);
            } else if f["ev"] == "Drop" && nums(&f["also_on_exits"]).contains(&row) {
                out.shared_drops.push(f);
            }
        }
    }
    out
}

/// The paths through a row's arms: sets of arms that run together. One arm
/// of each branch whose parent arm runs (or that has none); sequential
/// branches on one row combine.
fn arm_paths(arms: &[(usize, Option<usize>)]) -> Vec<Vec<usize>> {
    let mut branches: Vec<(usize, Option<usize>)> = arms.iter().map(|&(b, p)| (b, p)).collect();
    branches.sort();
    branches.dedup();
    let mut paths: Vec<Vec<usize>> = vec![Vec::new()];
    // Branches in order of nesting: a branch is decided once its parent is.
    let mut done: Vec<(usize, Option<usize>)> = Vec::new();
    while done.len() < branches.len() {
        let before = done.len();
        for &(br, parent) in &branches {
            if done.contains(&(br, parent)) || parent.is_some_and(|p| !done.iter().any(|&(b2, _)| arms.get(p).is_some_and(|a| a.0 == b2))) {
                continue;
            }
            let members: Vec<usize> = (0..arms.len()).filter(|&k| arms[k] == (br, parent)).collect();
            let mut next = Vec::new();
            for path in &paths {
                if parent.is_some_and(|p| !path.contains(&p)) {
                    next.push(path.clone());
                    continue;
                }
                for &m in &members {
                    let mut q = path.clone();
                    q.push(m);
                    next.push(q);
                }
            }
            paths = next;
            done.push((br, parent));
        }
        if done.len() == before {
            break;
        }
    }
    paths
}

/// Match the successor's MIR span exactly, including a backward edge or
/// the unit value at a join brace with no events.
fn end_fits(want: EndSpec, (row, to, col): (u32, u32, u32)) -> bool {
    match want {
        EndSpec::Row(r) => r == row,
        EndSpec::Edge([r, n]) => (r, n) == (row, to),
        EndSpec::EdgeCol([r, n, c]) => (r, n, c) == (row, to, col),
    }
}

/// Whether the dump's ends match `want` one to one (a multiset: two
/// edges ending on one row are two ends), in any order (a bipartite
/// matching, so overlapping specs can't steal each other's edge).
fn ends_match(want: &[EndSpec], got: &[(u32, u32, u32)]) -> bool {
    if want.len() != got.len() {
        return false;
    }
    fn augment(w: usize, want: &[EndSpec], got: &[(u32, u32, u32)], seen: &mut [bool], owner: &mut [Option<usize>]) -> bool {
        for g in 0..got.len() {
            if !seen[g] && end_fits(want[w], got[g]) {
                seen[g] = true;
                if owner[g].is_none_or(|o| augment(o, want, got, seen, owner)) {
                    owner[g] = Some(w);
                    return true;
                }
            }
        }
        false
    }
    let mut owner = vec![None; got.len()];
    (0..want.len()).all(|w| augment(w, want, got, &mut vec![false; got.len()], &mut owner))
}

fn kind_ok(want: &Option<String>, got: &str) -> bool {
    match want.as_deref() {
        None => true,
        Some("exclusive") => got == "mut" || got == "unique",
        Some(k) => k == got,
    }
}

/// Ok(()) or what the facts say instead.
fn check(a: &Assertion, facts: &[BodyF]) -> Result<(), String> {
    let b = body(facts, &a.func)?;
    match &a.check {
        Check::State { row, place, is } => {
            let r = row_after(b, *row);
            let st = r.and_then(|r| r.state.get(place)).map(String::as_str);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            let parts = r.and_then(|r| r.parts.get(place));
            let any_parts = parts.is_some_and(|(m, may)| !m.is_empty() || !may.is_empty());
            // `reserved` (a two-phase `&mut` before activation) lets others
            // read: not exclusive. `mut` and `unique` are.
            let excl = lent.iter().any(|l| matches!(l.kind.as_deref(), Some("mut" | "unique")));
            let readable = lent.iter().all(|l| matches!(l.kind.as_deref(), Some("shared" | "reserved" | "shallow")));
            let cause = match st {
                Some("maybe-moved") => Some("moved"),
                Some("maybe-unassigned") => Some("unassigned"),
                Some("maybe") => r.and_then(|r| r.cause.get(place)).map(String::as_str),
                _ => None,
            };
            let maybe = matches!(st, Some("maybe" | "maybe-moved" | "maybe-unassigned"));
            if maybe && cause.is_none() && matches!(is.as_str(), "moved*" | "unassigned*" | "maybe-moved" | "maybe-unassigned" | "maybe-imaginary") {
                return Err(format!("`maybe` without a cause after row {row}: the dump must distinguish moved from unassigned for {place}"));
            }
            let ok = match is.as_str() {
                "own" => st == Some("own") && lent.is_empty() && !any_parts,
                "shared" => st == Some("own") && !lent.is_empty() && readable,
                "mut" => matches!(st, Some("own" | "partly")) && excl,
                "moved" => st == Some("moved"),
                "maybe-moved" => maybe && cause == Some("moved"),
                // Moved only on an edge borrowck checks but that never runs
                // (an or-pattern's unreachable alternative): the dump must say
                // so itself. rustc's own verdict is the same as for a maybe-move.
                "maybe-imaginary" => maybe && cause == Some("imaginary"),
                "moved*" => st == Some("moved") || (maybe && matches!(cause, Some("moved" | "imaginary"))),
                "partly" => st == Some("partly"),
                "partly*" => st == Some("partly") || any_parts,
                "unassigned" => st == Some("unassigned"),
                "maybe-unassigned" => maybe && cause == Some("unassigned"),
                "unassigned*" => st == Some("unassigned") || (maybe && cause == Some("unassigned")),
                "absent" => st.is_none(),
                _ => false,
            };
            let got = format!("{} lent {:?} parts {:?}", st.unwrap_or("(no state for this row)"),
                lent.iter().map(|l| format!("{}:L{}->{}", l.kind.as_deref().unwrap_or("phase unknown"), l.loan, l.holders.join("|"))).collect::<Vec<_>>(), parts);
            if ok { Ok(()) } else { Err(got) }
        }
        Check::Lent { row, place, kind, holder, lender, absent } => {
            let r = row_after(b, *row);
            let lent: Vec<&Lent> = r.and_then(|r| r.lent.get(place)).into_iter().flatten().collect();
            if r.is_none() {
                return Err("(no state for this row)".into());
            }
            let lender_of = |l: &Lent| b.loans.iter().find(|x| x.id == l.loan).map(|x| x.lender.as_str());
            let candidates = lent.iter().filter(|l| {
                holder.as_deref().is_none_or(|h| h == "_" || l.holders.iter().any(|x| x == h))
                    && lender.as_deref().is_none_or(|w| lender_of(l) == Some(w))
            });
            let two_phase = |l: &Lent| b.loans.iter().find(|x| x.id == l.loan).is_some_and(|x| x.two_phase);
            // Only a two-phase loan can be reserved: the loan record must agree with the row.
            let hit = candidates.clone().any(|l| kind.is_none()
                || l.kind.as_deref().is_some_and(|k| kind_ok(kind, k) && (k != "reserved" || two_phase(l))));
            if !hit && matches!(kind.as_deref(), Some("reserved" | "exclusive" | "mut"))
                && candidates.clone().any(|l| l.kind.is_none())
            {
                return Err("the dump has no phase for this two-phase loan".into());
            }
            let got = format!("lent {:?}", lent.iter().map(|l| format!("{}:L{}->{}", l.kind.as_deref().unwrap_or("phase unknown"), l.loan, l.holders.join("|"))).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Loan(l) => {
            let cands: Vec<&LoanF> = b.loans.iter()
                .filter(|x| x.tracked && x.line == l.row && x.lender == l.lender && kind_ok(&l.kind, &x.kind)
                    && l.col.is_none_or(|c| x.col == Some(c))
                    && l.holder.as_deref().is_none_or(|h| h == "_" || x.holders.iter().any(|y| y == h)))
                .collect();
            // Ends per CFG edge, from the dump's BorrowEnd facts: (row, next row).
            let edges = |x: &LoanF| -> Vec<(u32, u32, u32)> { b.ends.iter().filter(|e| e.0 == x.id).map(|e| (e.1, e.2, e.3)).collect() };
            let fits = |x: &&LoanF| {
                // One end per (row, next row, column): MIR can have two CFG edges
                // between the same rows (a false edge), one path end.
                let mut e = edges(x);
                e.sort();
                e.dedup();
                // The loan record's end rows must agree too (a consumer of
                // the summary sees those).
                let summary_ok = |want: &Vec<EndSpec>| x.end_lines.as_ref().is_none_or(|el| {
                    let mut a: Vec<u32> = want.iter().map(|w| w.row()).collect();
                    let mut g = el.clone();
                    a.sort();
                    a.dedup();
                    g.sort();
                    g.dedup();
                    a == g
                });
                let rec = |r: &u32| x.end_lines.as_ref().is_none_or(|el| el.contains(r));
                let not_rec = |r: &u32| x.end_lines.as_ref().is_none_or(|el| !el.contains(r));
                l.ends.as_ref().is_none_or(|want| ends_match(want, &e) && summary_ok(want))
                    && l.ends_include.iter().all(|r| e.iter().any(|g| g.0 == *r) && rec(r))
                    && !l.ends_exclude.iter().any(|r| e.iter().any(|g| g.0 == *r) || !not_rec(r))
            };
            let hit = cands.iter().any(fits);
            let show = |x: &LoanF| format!("{} {} (col {:?}) -> {:?} ends (row, next) {:?}, record {:?}", x.kind, x.lender, x.col, x.holders, edges(x), x.end_lines);
            let got = if cands.is_empty() {
                format!("loans on row {}: {:?}", l.row, b.loans.iter().filter(|x| x.line == l.row).map(show).collect::<Vec<_>>())
            } else {
                format!("{:?}", cands.iter().map(|x| show(x)).collect::<Vec<_>>())
            };
            if l.absent { if cands.is_empty() { Ok(()) } else { Err(got) } } else if hit { Ok(()) } else { Err(got) }
        }
        Check::Drop { row, place, how, absent } => {
            let fs = row_facts(b, *row);
            let drops: Vec<&Value> = fs.events().filter(|f| {
                let ev = f["ev"].as_str().unwrap_or("");
                (ev == "Drop" || ev == "ScopeEnd") && f["path"].as_str() == Some(place.as_str())
            }).collect();
            let hit = drops.iter().any(|f| {
                let h = f["how"].as_str().unwrap_or("");
                let scope_end = f["ev"] == "ScopeEnd";
                match how.as_str() {
                    "definite" => h == "drops",
                    "conditional" => h == "drops_if_init",
                    "rest" => h == "drops_rest",
                    "none" => scope_end || h == "nothing_to_drop",
                    _ => !scope_end && h != "nothing_to_drop",
                }
            });
            if *absent && !hit && fs.may_drop(place) {
                return Err(format!("shared drop of {place} has no drop kind for this exit"));
            }
            let got = format!("{:?}", drops.iter().map(|f| f.to_string()).collect::<Vec<_>>());
            if hit != *absent { Ok(()) } else { Err(got) }
        }
        Check::Event { row, ev, absent } => {
            let p = Pat::parse(ev)?;
            let row = row_facts(b, *row);
            let fs: Vec<_> = row.events().collect();
            let hit = fs.iter().any(|f| p.matches(f));
            if *absent && !hit && p.kind == "drop" && row.may_drop(&p.place) {
                return Err(format!("shared drop of {} may run on this exit", p.place));
            }
            if hit != *absent { Ok(()) } else { Err(format!("row facts: {}", brief(&fs))) }
        }
        Check::Order { row, events, exact_drops } => {
            if b.version.is_none() {
                return Err("spike dumps sort events by kind and have no arm membership to prove order on one path".into());
            }
            let pats: Vec<Pat> = events.iter().map(|e| Pat::parse(e)).collect::<Result<_, _>>()?;
            let fs = row_facts(b, *row).located;
            // A v1 producer moved an early-exit drop to the exit row but took
            // its `arm` at the original cleanup location.
            if b.version == Some(1) && fs.iter().any(|f| f["early_exit"].is_u64()) {
                return Err("a v1 early-exit drop's arm is not the exit's: order cannot be proved on one path".into());
            }
            // One sequence per path through the row: facts outside any arm
            // plus those of one choice of arms (one arm per branch whose
            // parent arm runs; sequential branches on one row combine).
            let arms = b.rows.get(row).map_or(&[][..], |r| &r.arms[..]);
            let in_order = |path: &[usize]| {
                let mut k = 0;
                let mut drops = 0;
                for f in &fs {
                    let arm = f["arm"].as_u64().map(|a| a as usize);
                    if arm.is_none_or(|a| path.contains(&a)) {
                        drops += (f["ev"] == "Drop") as usize;
                        if k < pats.len() && pats[k].matches(f) {
                            k += 1;
                        }
                    }
                }
                // `exact_drops`: the path runs no destructor the order doesn't name.
                k == pats.len() && (!*exact_drops || drops == pats.iter().filter(|p| p.kind == "drop").count())
            };
            if arm_paths(arms).iter().any(|p| in_order(p)) { Ok(()) } else { Err(format!("row facts in order: {}", brief(&fs))) }
        }
    }
}

fn brief(fs: &[&Value]) -> String {
    fs.iter().map(|f| {
        let s = |k: &str| f[k].as_str().unwrap_or("").to_owned();
        match s("ev").as_str() {
            "Move" | "Copy" => format!("{} {} -> {}", s("ev").to_lowercase(), s("path"), s("to")),
            "Borrow" => format!("borrow {} {} -> {}", s("kind"), s("lender"), s("holder")),
            "BorrowEnd" => format!("end {} -> {}", s("lender"), s("holder")),
            "Init" => format!("init {}", s("path")),
            "Drop" => format!("drop {} [{}]", s("path"), s("how")),
            "Repoint" => format!("repoint {}", s("holder")),
            e => format!("{} {}", e, s("path")),
        }
    }).collect::<Vec<_>>().join("; ")
}

#[test]
fn rv3_issue_cases_against_facts() {
    let all = cases();
    let strict = std::env::var("RV3_ISSUES_STRICT").is_ok_and(|v| v == "1");
    let jobs: usize = std::env::var("RV3_JOBS").ok().and_then(|v| v.parse().ok()).unwrap_or(4);
    let next = std::sync::atomic::AtomicUsize::new(0);
    let results = std::sync::Mutex::new(Vec::new());
    std::thread::scope(|sc| {
        for _ in 0..jobs {
            sc.spawn(|| loop {
                let i = next.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
                let Some((name, src, text)) = all.get(i) else { break };
                let case: Case = match toml::from_str(text) {
                    Ok(c) => c,
                    Err(e) => {
                        results.lock().unwrap().push((name.clone(), None, Err(format!("parse: {e}"))));
                        continue;
                    }
                };
                let dir = std::env::var("RV3_FACTS_DIR").ok();
                let r = facts_of(dir.as_deref(), name, src, case.known_crash.as_ref()).and_then(|v| v.map(|v| load_facts(&v)).transpose());
                results.lock().unwrap().push((name.clone(), Some(case), r));
            });
        }
    });
    let mut results = results.into_inner().unwrap();
    results.sort_by(|a, b| a.0.cmp(&b.0));
    if results.is_empty() || results.iter().all(|(_, _, r)| matches!(r, Ok(None))) {
        let why = if results.is_empty() { "no cases (RV3_ISSUES_ONLY / RV3_JOBS?)" } else { "the installed plugin writes no RV3_FACTS dump (no fact layer)" };
        assert!(!strict, "RV3_ISSUES_STRICT=1 but no facts were checked: {why}");
        eprintln!("rv3_issue_cases_against_facts: skipped: {why}");
        return;
    }
    let mut report = String::new();
    let (mut pass, mut total) = (0, 0);
    let (mut a_pass, mut a_total) = (BTreeMap::<String, (usize, usize)>::new(), 0);
    let mut by_phase: BTreeMap<String, (usize, usize)> = BTreeMap::new();
    let mut unexpected = Vec::new();
    let mut checked = 0;
    for (name, case, r) in &results {
        total += 1;
        let Some(case) = case else {
            let _ = writeln!(report, "FAIL {name}: {}", r.as_ref().err().unwrap());
            unexpected.push(name.clone());
            continue;
        };
        // No facts for a case (a plugin failure, an unreadable or missing
        // dump) checks nothing: never an expected failure.
        let facts = match r {
            Ok(Some(f)) => f,
            Ok(None) => {
                let _ = writeln!(report, "FAIL {name}: no fact dump (while other cases have one)");
                unexpected.push(format!("{name} (no dump)"));
                continue;
            }
            Err(e) => {
                let _ = writeln!(report, "FAIL {name}: {e}");
                unexpected.push(format!("{name} (no facts read)"));
                continue;
            }
        };
        checked += 1;
        let mut fails = Vec::new();
        for a in assertions(case) {
            a_total += 1;
            let e = a_pass.entry(a.src.clone()).or_default();
            e.1 += 1;
            match check(&a, facts) {
                Ok(()) => e.0 += 1,
                Err(got) => fails.push(format!("    [{}] {}: got {}", a.src, a.what, got)),
            }
        }
        let ok = fails.is_empty();
        let phase = case.xfail.clone().unwrap_or_else(|| "-".into());
        let ph = by_phase.entry(phase.clone()).or_default();
        ph.1 += 1;
        if ok {
            pass += 1;
            ph.0 += 1;
        }
        let tag = match (ok, &case.xfail) {
            (true, None) => "pass",
            (true, Some(_)) => {
                unexpected.push(format!("{name} (passes: remove xfail)"));
                "PASS (xfail)"
            }
            (false, Some(_)) => "xfail",
            (false, None) => {
                unexpected.push(name.clone());
                "FAIL"
            }
        };
        let crash = case.known_crash.as_ref().map_or(String::new(), |k| format!(", known_crash {} at {}", k.phase, k.panic_at));
        let _ = writeln!(report, "{tag} {name} (#{}, {}, xfail {phase}{crash})", case.issue, case.cluster);
        for f in fails {
            let _ = writeln!(report, "{f}");
        }
    }
    let _ = writeln!(report, "\n{pass} of {total} issue tests pass");
    for (src, (p, t)) in &a_pass {
        let _ = writeln!(report, "  {src} assertions: {p} of {t} hold");
    }
    let _ = writeln!(report, "  ({a_total} assertions)");
    for (ph, (p, t)) in &by_phase {
        let _ = writeln!(report, "  xfail {ph}: {p} of {t} pass");
    }
    if let Ok(out) = std::env::var("RV3_ISSUES_REPORT") {
        std::fs::write(&out, &report).unwrap();
    }
    eprintln!("{report}");
    if strict {
        assert!(checked > 0, "RV3_ISSUES_STRICT=1 but no case's facts were read");
        assert!(unexpected.is_empty(), "RV3 issue tests: unexpected results:\n  {}", unexpected.join("\n  "));
    }
}

